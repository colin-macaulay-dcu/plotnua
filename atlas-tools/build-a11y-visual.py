"""
JOB 5 · SHARED VISUAL ACCESSIBILITY LAYER
===============================================================================
Four proven Job 3 findings and nothing else: D contrast, E reduced motion,
F the infinite My Plot pulse, B carousel-dot hit targets.

WHY ONE APPENDED BLOCK PER PAGE RATHER THAN EDITING THE EXISTING RULES.
The failing declarations are not page-specific: `.footer-base` is one literal
duplicated across 21 pages, `.sub` also exists on index, `.d-tag` also exists
on your-plot, and `.n` exists on fourteen pages. Editing those declarations in
place would silently repaint surfaces this job never measured. So each page
gets ONE clearly marked override block carrying only the rules that page's own
measured failures need. A reader can delete the block and have the page back.

WHY NOT CHANGE THE BRAND TOKENS. --brand-sage #8FAF8A fails on ivory (2.22)
and PASSES on the dark ground (5.03, which is why the footer headings only
needed their opacity removed). Retuning the token would fix one and break the
other, and would reach surfaces outside this job. The overrides are scoped.

THE COLOURS. Each is the minimum move along the SAME hue and saturation that
reaches WCAG AA at the text's real size, computed against the real painted
background, not guessed:

  .footer-col h2   opacity .85 -> 1       4.10 -> 5.03   NO colour change
  .discover .lede  --accent -> --brand-sage  2.05 -> 5.03   existing token
  .footer-base     #7C7565 -> #A39D8E     2.66 -> 4.51
  .d-tag (404)     --oak   -> #B49979     2.60 -> 4.51
  .sub   (404)     #9C9587 -> #A39D90     4.10 -> 4.52
  sage on ivory    #8FAF8A -> #557550     2.22 -> 4.76  (.related-kicker,
                   (.n, on paper)         2.11 -> 4.51   .r-kicker, .step-num)

#557550 clears every ivory/paper ground this job touches (measured 4.76 on
ivory, 4.51 on the slightly darker paper) and stays
well below the ink used for primary copy (11.18), so muted text stays muted.

REDUCED MOTION reuses the homepage's own established treatment verbatim --
    .reveal{ opacity:1 !important; transform:none !important; transition:none !important; }
-- which its author wrote precisely because a 1.1s fade met the visitor five
times per page. The same principle is extended to the surfaces that never got
it, plus the shared brand mark, the 404 hero and the My Plot screens, and the
My Plot status pulse is stopped. Nothing that communicates STATE is removed:
the pulse's element, colour and meaning are untouched, only its endless
animation stops for people who asked for less movement.

CAROUSEL DOTS keep their painted 7px/10px exactly. A transparent ::after gives
each one a 24x24 hit target, and the row gap goes 9px -> 17px so centres sit
24px apart -- without that, 24px targets would overlap and the neighbour would
steal the click. Row width grows about 199px -> 303px, which still fits 390px.

    python3 atlas-tools/build-a11y-visual.py            apply
    python3 atlas-tools/build-a11y-visual.py --check    verify, write nothing
    python3 atlas-tools/build-a11y-visual.py --revert   undo
"""

