def build(write=True):
    # ---- S0 · protected state, asserted BEFORE anything is written -------
    d25 = (ROOT / DISC025).read_text(encoding="utf-8")
    i, j = d25.find("<main"), d25.rfind("</main>")
    if sha(d25[i:j + 7]) != DISC025_MAIN_SHA:
        die("S0 DISC-025 frozen <main> hash has already moved")
    for f, want in FROZEN.items():
        if sha((ROOT / f).read_bytes()) != want:
            die("S0 %s is not at its frozen hash" % f)
    if DISC025 in plan():
        die("S0 DISC-025 appears in the plan; it must never be a target")
    if "search.css" in plan():
        die("S0 search.css appears in the plan; Search V1 is frozen")

    results = []
    for f, parts in plan().items():
        p = ROOT / f
        if not p.exists():
            die("target %s does not exist" % f)
        base = p.read_text(encoding="utf-8")
        clean = strip_block(base)                 # idempotent: drop any old block
        block = BEGIN + "\n" + "\n".join(parts) + "\n" + END
        k = clean.rfind("</style>")
        if k < 0:
            die("%s has no </style> to append the block to" % f)
        out = clean[:k] + "\n" + block + "\n" + clean[k:]
        results.append({"file": f, "base": base, "clean": clean, "out": out,
                        "delta": len(out) - len(base), "parts": len(parts)})

    # ---- GUARDS ----------------------------------------------------------
    for r in results:
        f, out, base, clean = r["file"], r["out"], r["base"], r["clean"]

        # V1 · exactly one marked block
        if out.count(BEGIN) != 1 or out.count(END) != 1:
            die("V1 %s has %d begin / %d end markers; exactly one each is required"
                % (f, out.count(BEGIN), out.count(END)))

        # V2 · everything outside the block is byte-identical to the base
        if strip_block(out) != clean:
            die("V2 %s changed outside its own override block" % f)

        # V3 · the block is inside a <style>, not loose in the body.
        #      The counts must ignore comments and <script> bodies: 404.html
        #      mentions "<style" inside one, which left the raw tally at
        #      opens=2 closes=1 and made this test unable to fail on that page.
        #      The capability proof found that blindness; masking length-
        #      preservingly (as Job 4's L8 had to) makes every page balanced.
        def style_counts(s):
            blank = lambda m: " " * len(m.group(0))
            s = re.sub(r"<!--.*?-->", blank, s, flags=re.S)
            s = re.sub(r"<script[^>]*>.*?</script>", blank, s, flags=re.S | re.I)
            return s.count("<style"), s.count("</style>")
        before = out[:out.index(BEGIN)]
        opens, closes = style_counts(before)
        if opens <= closes:
            die("V3 %s puts the block outside any <style> element" % f)

        # V4 · no homeowner-visible text added. The block is CSS only, so any
        #      content:"" other than the dot's empty one is a red flag.
        blk = out[out.index(BEGIN):out.index(END)]
        if re.search(r'content\s*:\s*"[^"]+"', blk):
            die("V4 %s injects visible generated content" % f)

        # V5 · no brand token redefined; the overrides must stay scoped
        if re.search(r"--(brand-sage|accent|oak|ink|soft)\s*:", blk):
            die("V5 %s redefines a brand token; the fix must stay scoped" % f)

        # V6 · Search V1 markup untouched on the page
        for frag in ('<a class="pns-pill"', 'id="pnsInput"', 'src="search.js"'):
            if base.count(frag) != out.count(frag):
                die("V6 %s changed Search V1 markup (%s)" % (f, frag))

        # V7 · Job 4's contract untouched
        for frag in ('<main id="pn-main">', 'class="pn-skip"',
                     '<nav class="footer-cols" aria-label="Footer">', 'role="group"'):
            if base.count(frag) != out.count(frag):
                die("V7 %s changed the Job 4 landmark/skip/footer contract (%s)"
                    % (f, frag))

        # V8 · no font-size change anywhere in the block. Contrast may not be
        #      bought by making text bigger.
        if re.search(r"font-size\s*:", blk):
            die("V8 %s changes a font-size; contrast must be fixed with colour" % f)

    if not write:
        print("\n  --check: %d files would change, nothing written.\n" % len(results))
        for r in results:
            print("    %-44s %+6d  %d fragment(s)" % (r["file"], r["delta"], r["parts"]))
        print("\n  8 guard families passed.\n")
        return results

    for r in results:
        (ROOT / r["file"]).write_text(r["out"], encoding="utf-8")
    print("\n  wrote %d files.\n" % len(results))
    for r in results:
        print("    %-44s %+6d  %d fragment(s)" % (r["file"], r["delta"], r["parts"]))
    print("\n  8 guard families passed.\n")
    return results


def revert():
    files = sorted(plan())
    subprocess.run(["git", "checkout", "--"] + files, cwd=str(ROOT), check=True)
    print("reverted %d files" % len(files))


if __name__ == "__main__":
    if "--revert" in sys.argv:
        revert()
    else:
        build(write="--check" not in sys.argv)
