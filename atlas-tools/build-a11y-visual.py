def die(msg):
    print("REFUSED: " + msg + " -- nothing written")
    sys.exit(2)


def sha(s):
    return hashlib.sha256(s.encode("utf-8") if isinstance(s, str) else s).hexdigest()


def strip_block(t):
    """Removes EXACTLY what the splice inserts -- one leading newline, the
    block, one trailing newline. An earlier version used \n* and greedily ate
    a newline that was already in the file, so the round trip was not
    symmetric and guard V2 refused its own output."""
    return re.sub(r"\n" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n",
                  "", t, flags=re.S)


