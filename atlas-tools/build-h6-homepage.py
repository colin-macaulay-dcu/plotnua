#!/usr/bin/env python3
"""H6 · HOMEPAGE GARDEN COMPONENT ("Discover What's Possible"), staging candidate, 25 Oct 2026.

Replaces the Possibility Reveal component (L2B/H5C4) in index.html#heroStage with the founder-approved H6 garden
experience: an empty garden (image set v6), floating lettering, five garden discoveries, House as a Power Station with
its eight scenes and persistent navigation, Show All / Clear All.

  python3 atlas-tools/build-h6-homepage.py --source PROTOTYPE_INDEX   build assets/h6/stage-snippet.part + record
  python3 atlas-tools/build-h6-homepage.py --mount                    mount the snippet and the head links in index.html
  python3 atlas-tools/build-h6-homepage.py --check                    guard (no source needed)

MECHANICAL TRANSFORM of the approved prototype block only:
  1. image paths point to assets/h6/img/ and become responsive (AVIF/WebP for the photograph; WebP with exact
     transparency for every layer); the same widths and sizes for every layer keep them in register;
  2. discovery layers carry data-srcset only (nothing but the photograph and the lettering loads on arrival);
     the Ground scene's X-ray image carries data-href and is armed when that scene starts;
  3. the prototype comments become release comments. Markup, ids, copy and behaviour are otherwise unchanged.

The guard refuses if: a component file differs from its record; the snippet is not mounted verbatim in #heroStage;
the old Possibility Reveal component, its stylesheets or scripts are still loaded by the homepage; index.html carries
other than exactly one <h1>; an id is un-prefixed or a reserved homepage id is reused; a CSS rule is unscoped; a
discovery layer would load with the page; an image the snippet references is missing or differs from its record;
the AI label is missing; or the Atlas figures block, analytics or consent differ from the record's homepage baseline."""
import re, sys, os, json, hashlib
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
H6 = 'assets/h6/'
RECORD = os.path.join(ROOT, H6 + 'h6-record.json')
SNIP = H6 + 'stage-snippet.part'
FILES = [H6 + 'h6.css', H6 + 'h6.js', SNIP]
OPEN, CLOSE = '<!-- H6 GARDEN COMPONENT · BEGIN (generated by atlas-tools/build-h6-homepage.py; do not hand-edit) -->', '<!-- H6 GARDEN COMPONENT · END -->'
PR_OPEN, PR_CLOSE = '<!-- POSSIBILITY REVEAL · L2B v2 component', '<!-- /POSSIBILITY REVEAL -->'
SLOT_OLD = '<div class="hero-stage p4-stage" id="heroStage" data-hero="possibility-reveal">'
SLOT = '<div class="hero-stage p4-stage" id="heroStage" data-hero="h6">'
HEAD = ['<link rel="stylesheet" href="assets/h6/h6.css">', '<script src="assets/h6/h6.js" defer></script>']
PR_HEAD = re.compile(r'<link rel="stylesheet" href="assets/possibility-reveal/[^"]+">\n|<script src="assets/possibility-reveal/[^"]+" defer></script>\n|<link rel="preload" as="image"[^>]*possibility-reveal[^>]*>\n')
HERO_COMMENT = ('<!-- ================================================================\n'
                '         HERO STAGE · H6 GARDEN ("Discover What\'s Possible")\n'
                '         The garden experience mounts here. The markup between the H6 GARDEN COMPONENT\n'
                '         markers is generated by atlas-tools/build-h6-homepage.py from the founder-approved\n'
                '         H6 prototype: do not hand-edit it. Its styles and script load from assets/h6/,\n'
                '         its images from assets/h6/img/ (held to assets/h6/h6-record.json).\n'
                '         ================================================================ -->')
W = (960, 1677); SIZES = '(max-width: 700px) 100vw, 1677px'
RESERVED = ['heroFrame','heroPhoto','heroCardsDock','heroCopy','heroWordmark','brandMark','atlasFigures','dCarousel',
            'pn-main','top','discover','research','libInfoBtn','libInfo','continuePanel','pnsOpen','heroStage']
AI_LABEL = 'AI-generated illustration'
LAYERS = {'treehouse': 'H6-layer-treehouse', 'borrowed-garden': 'H6-layer-borrowed-garden', 'garden-room': 'H6-layer-garden-room',
          'wildlife-pond': 'H6-layer-wildlife-pond', 'garden-retreat': 'H6-layer-garden-retreat', 'power-station': 'H6-layer-power-station'}

def sha(b): return hashlib.sha256(b if isinstance(b, bytes) else b.encode('utf-8')).hexdigest()
def rd(p): return open(os.path.join(ROOT, p), encoding='utf-8').read()
def die(m): print('REFUSED: ' + m); sys.exit(1)
def srcset(stem, ext): return ', '.join('assets/h6/img/%s-%d.%s %dw' % (stem, w, ext, w) for w in W)

def transform(block):
    def one(t, a, b):
        if t.count(a) != 1: die('anchor not found exactly once: ' + a[:90])
        return t.replace(a, b)
    t = block
    t = re.sub(r'<!-- H6 POSSIBILITY REVEAL · LOCAL PROTOTYPE v5.*?-->\n', '', t, count=1, flags=re.S)
    t = t.replace('<!-- /H6 POSSIBILITY REVEAL · LOCAL PROTOTYPE -->', '').rstrip() + '\n'
    alt = re.search(r'<img class="h6p-base"[^>]*?alt="([^"]+)">', t, flags=re.S).group(1)
    t = re.sub(r'<img class="h6p-base"[^>]*?>', (
        '<picture><source type="image/avif" srcset="%s" sizes="%s"><source type="image/webp" srcset="%s" sizes="%s">'
        '<img class="h6p-base" src="assets/h6/img/H6-garden-base-v6-1677.webp" width="1677" height="938" fetchpriority="high" decoding="async" alt="%s"></picture>'
        % (srcset('H6-garden-base-v6', 'avif'), SIZES, srcset('H6-garden-base-v6', 'webp'), SIZES, alt)), t, count=1, flags=re.S)
    for idd, stem in (('h6p-letter-shadow', 'H6-lettering-shadows'), ('h6p-letter', 'H6-lettering-letters')):
        t = re.sub(r'(<img class="h6p-letter is-off" id="%s") src="[^"]+"' % idd,
                   r'\1 src="assets/h6/img/%s-1677.webp" srcset="%s" sizes="%s"' % (stem, srcset(stem, 'webp'), SIZES), t, count=1)
    for k, stem in LAYERS.items():
        t = re.sub(r'(<img class="h6p-ov" data-d="%s")\s+data-src="[^"]+"' % k,
                   r'\1 data-srcset="%s" data-sizes="%s"' % (srcset(stem, 'webp'), SIZES), t, count=1)
    t = re.sub(r'(<img class="h6p-fix" id="h6p-retreat-patch") data-src="[^"]+"',
               r'\1 data-srcset="%s" data-sizes="%s"' % (srcset('H6-layer-garden-retreat-lawn-patch', 'webp'), SIZES), t, count=1)
    t = t.replace('href="assets/h6-prototype/img/H6-empty-garden-base.png"', 'data-href="assets/h6/img/H6-garden-base-v6-960.webp"')
    if 'assets/h6-prototype/' in t or 'data-src=' in t: die('a prototype path or an unconverted data-src remains')
    return OPEN + '\n' + t + CLOSE

def build(src):
    h = open(src, encoding='utf-8').read()
    a = h.index('<!-- H6 POSSIBILITY REVEAL · LOCAL PROTOTYPE v5'); b = h.index('<!-- /H6 POSSIBILITY REVEAL · LOCAL PROTOTYPE -->') + len('<!-- /H6 POSSIBILITY REVEAL · LOCAL PROTOTYPE -->')
    snip = transform(h[a:b])
    open(os.path.join(ROOT, SNIP), 'w', encoding='utf-8').write(snip)
    return snip

def baseline_parts(index):
    """The parts of the homepage H6 must never touch, as recorded at mount time."""
    m = re.search(r'<dl class="atlas-figures" id="atlasFigures".*?</dl>', index, flags=re.S)
    heads = re.findall(r'<script[^>]*(?:Cookiebot|googletagmanager)[^>]*>\s*</script>|<script>\s*window\.dataLayer.*?</script>', index, flags=re.S)
    block = m.group(0) if m else ''
    # The daily Atlas workflow (.github/scripts/atlas_stats.py) owns exactly six numbers in this block: the
    # three data- attributes and the three <dt> values. They are blanked before hashing, so a figures update
    # never trips this guard; everything else in the block must stay byte-identical. The numbers themselves
    # are checked against atlas-stats.json by .github/scripts/check_atlas_figures.py.
    block = re.sub(r'(data-(?:products|suppliers|prices)=")\d+(")', r'\1#\2', block)
    block = re.sub(r'(<dt id="atlas(?:Products|Suppliers|Prices)">)\d+(</dt>)', r'\1#\2', block)
    return {'atlas_figures_block': sha(block), 'analytics_and_consent': sha('\n'.join(heads)), 'analytics_and_consent_count': len(heads)}

def mount():
    p = os.path.join(ROOT, 'index.html'); idx = open(p, encoding='utf-8').read()
    snip = rd(SNIP)
    if OPEN in idx: a = idx.index(OPEN); b = idx.index(CLOSE) + len(CLOSE); idx = idx[:a] + snip + idx[b:]
    else:
        a = idx.find(PR_OPEN); b = idx.find(PR_CLOSE)
        if a < 0 or b < 0: die('index.html has neither the H6 nor the Possibility Reveal mount markers')
        idx = idx[:a] + snip + idx[b + len(PR_CLOSE):]
    if idx.count(SLOT_OLD) == 1: idx = idx.replace(SLOT_OLD, SLOT)
    idx = re.sub(r'<!-- =+\n\s+HERO STAGE · POSSIBILITY REVEAL.*?=+ -->', HERO_COMMENT, idx, count=1, flags=re.S)
    idx = PR_HEAD.sub('', idx)
    if HEAD[0] not in idx:
        anchor = '<!-- PLOTNUA HEADER v2 · HEAD · END -->\n'
        if idx.count(anchor) != 1: die('head anchor not found')
        idx = idx.replace(anchor, anchor + '<link rel="preload" as="image" type="image/avif" imagesrcset="%s" imagesizes="%s" fetchpriority="high">\n%s\n%s\n'
                          % (srcset('H6-garden-base-v6', 'avif'), SIZES, HEAD[0], HEAD[1]))
    open(p, 'w', encoding='utf-8').write(idx)
    return idx

def scoped_css(css):
    bad = []; plain = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    def walk(t):
        i = 0
        while True:
            j = t.find('{', i)
            if j < 0: return
            head = t[i:j].strip()
            if head.startswith('@font-face'):   # only H6's own metric-matched fallback face is allowed
                k = t.find('}', j) + 1
                if not re.search(r'font-family:\s*"H6 [^"]+"', t[j:k]): bad.append('a @font-face that is not H6\'s own')
                i = k; continue
            if head.startswith(('@media', '@supports', '@keyframes')):
                d = 1; k = j + 1
                while d: d += t[k] == '{'; d -= t[k] == '}'; k += 1
                if head.startswith('@keyframes'):
                    if not head.split()[1].startswith(('h6p-', 'psb-')): bad.append('unprefixed keyframes ' + head)
                else: walk(t[j + 1:k - 1])
                i = k; continue
            for sel in head.split(','):
                if not re.match(r'^(\.h6p\b|\.h6p-|\.psb-|#h6p)', sel.strip()): bad.append('unscoped CSS selector: ' + sel.strip()[:70])
            i = t.find('}', j) + 1
    walk(plain); return bad

def guard():
    bad = []
    rec = json.load(open(RECORD))
    for p in FILES:
        if sha(open(os.path.join(ROOT, p), 'rb').read()) != rec['files'].get(p): bad.append(p + ' differs from its record (hand-edited?)')
    for p, h in rec['images'].items():
        f = os.path.join(ROOT, p)
        if not os.path.exists(f): bad.append(p + ' is missing')
        elif sha(open(f, 'rb').read()) != h: bad.append(p + ' differs from its record')
    snip, css, js = rd(SNIP), rd(H6 + 'h6.css'), rd(H6 + 'h6.js')
    index = rd('index.html')
    if index.count(snip) != 1: bad.append('the H6 snippet is not mounted verbatim exactly once in index.html')
    if index.count(SLOT) != 1: bad.append('#heroStage is not the H6 slot')
    a = index.find(SLOT); b = index.find(OPEN)
    if not (0 <= a < b and index[a + len(SLOT):b].strip() == ''): bad.append('the H6 snippet is not mounted directly inside #heroStage')
    for tag in HEAD:
        if index.count(tag) != 1: bad.append(tag + ' is not loaded exactly once')
    if 'assets/possibility-reveal/' in index or PR_OPEN in index or 'data-pr-root' in index.replace("querySelector('#heroStage [data-pr-root]')", ''):
        bad.append('the retired Possibility Reveal component, or one of its files, is still loaded by the homepage')
    if len(re.findall(r'<h1\b', index)) != 1: bad.append('index.html must carry exactly one <h1>')
    if snip.count('<h1 class="h6p-title" id="h6p-title">') != 1: bad.append('the page H1 is not the H6 invitation')
    for i in re.findall(r'\bid="([^"]+)"', snip):
        if not i.startswith(('h6p', 'psb-', 'm-', 'h6p-')): bad.append('un-prefixed id in the component: ' + i)
        if i in RESERVED: bad.append('reserved homepage id reused: ' + i)
    bad += scoped_css(css)
    # nothing but the photograph and the lettering loads on arrival
    for m in re.finditer(r'<img class="h6p-(?:ov|fix)"[^>]*>', snip):
        if re.search(r'\s(?:src|srcset)=', m.group(0)): bad.append('a discovery layer would load with the page: ' + m.group(0)[:80])
    if re.search(r'<image[^>]*\shref=', snip): bad.append('an SVG scene image would load with the page')
    for u in set(re.findall(r'assets/h6/img/[A-Za-z0-9._-]+', snip)):
        if u not in rec['images']: bad.append(u + ' is referenced but not recorded')
    plain = re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', ' ', snip))
    if AI_LABEL not in plain: bad.append('the AI label "%s" is missing' % AI_LABEL)
    if 'TimberIN' in snip: bad.append('a supplier is named beside the AI illustration')
    if 'document.write' in js or 'eval(' in js: bad.append('the script uses document.write or eval')
    # the homepage outside H6 is untouched where it matters
    base = rec.get('homepage_baseline') or {}
    now = baseline_parts(index)
    for k in ('atlas_figures_block', 'analytics_and_consent', 'analytics_and_consent_count'):
        if base.get(k) != now[k]: bad.append('the homepage ' + k.replace('_', ' ') + ' differs from its recorded baseline')
    return bad

def write_record(index_before_mount):
    imgs = {}
    for f in sorted(os.listdir(os.path.join(ROOT, H6 + 'img'))):
        p = H6 + 'img/' + f; imgs[p] = sha(open(os.path.join(ROOT, p), 'rb').read())
    rec = {'schema': 'plotnua.h6-component.v1', 'what_this_is': __doc__.split('\n\n')[0],
           'files': {p: sha(open(os.path.join(ROOT, p), 'rb').read()) for p in FILES}, 'images': imgs,
           'homepage_baseline': baseline_parts(index_before_mount),
           'baseline_note': 'Atlas figures block and analytics/consent tags as they stood when H6 was mounted. The daily Atlas workflow '
                            'changes the figures: re-run --mount (which re-records the baseline) only after reviewing that diff.'}
    json.dump(rec, open(RECORD, 'w'), indent=1); open(RECORD, 'a').write('\n')

if __name__ == '__main__':
    if '--source' in sys.argv:
        build(sys.argv[sys.argv.index('--source') + 1]); print('built ' + SNIP)
    if '--mount' in sys.argv:
        before = rd('index.html'); mount(); write_record(before); print('mounted; record written')
    if '--check' in sys.argv:
        bad = guard()
        if bad: print('H6 COMPONENT CHECK FAILED'); [print('  - ' + b) for b in bad]; sys.exit(1)
        print('H6 COMPONENT CHECK OK')
