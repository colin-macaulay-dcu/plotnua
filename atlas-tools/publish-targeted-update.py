def fetch_snapshot(org_id, products):
    """Read-only Atlas read of one organisation's records with AIRTABLE_TOKEN.
    Not exercised by the regression tests (no token in the build container)."""
    token = os.environ.get("AIRTABLE_TOKEN")
    if not token:
        refuse("--fetch needs AIRTABLE_TOKEN in the environment; or pass --snapshot")
    base = "appoLZFWesvoPhZGR"
    tables = {"products": "tblMiUcO4OT9ia2aE", "pricing": "tblqsjmkTrwSct7gv",
              "availability": "tblP1d5lgKxxhkBkj", "featureValues": "tbl7wGyTgJ2mzjdOh",
              "features": "tblH2EpBiV9bt1rdD", "organisations": "tblngwmviAcWxFKsW",
              "assets": "tblFMzOKcNQTjXVYS"}

    def get(table, formula=None):
        out, offset = [], None
        while True:
            q = {"pageSize": "100"}
            if formula:
                q["filterByFormula"] = formula
            if offset:
                q["offset"] = offset
            url = "https://api.airtable.com/v0/%s/%s?%s" % (base, table, urllib.parse.urlencode(q))
            req = urllib.request.Request(url, headers={"Authorization": "Bearer " + token})
            with urllib.request.urlopen(req, timeout=60) as r:
                d = json.loads(r.read())
            out += d.get("records", [])
            offset = d.get("offset")
            if not offset:
                return out

    org = get(tables["organisations"], "RECORD_ID()='%s'" % org_id)
    if len(org) != 1:
        refuse("organisation %s not found in Atlas" % org_id)
    name = org[0]["fields"].get("Organisation Name", "")
    prods = [p for p in get(tables["products"], "FIND('%s', ARRAYJOIN({Organisation}))"
                            % name.replace("'", "\\'"))
             if org_id in link_ids(p, "Organisation")]
    if products:
        prods = [p for p in prods if p["id"] in products]
    ids = {p["id"] for p in prods}

    def linked(table, field="Product"):
        rows = []
        for p in prods:
            rows += get(table, "FIND('%s', ARRAYJOIN({%s}))"
                        % (p["fields"].get("Product Name", "").replace("'", "\\'"), field))
        seen, out = set(), []
        for r in rows:
            if r["id"] not in seen and set(link_ids(r, field)) & ids:
                seen.add(r["id"])
                out.append(r)
        return out

    fvals = linked(tables["featureValues"])
    feats = {i for r in fvals for i in link_ids(r, "Feature")}
    assets = [a for a in get(tables["assets"], "FIND('%s', ARRAYJOIN({Organisations}))"
                             % name.replace("'", "\\'"))
              if link_ids(a, "Organisations") == [org_id]]
    return {"source": "Atlas read %s (publish-targeted-update --fetch)"
                      % _dt.datetime.now(_dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "products": prods, "pricing": linked(tables["pricing"]),
            "availability": linked(tables["availability"]), "featureValues": fvals,
            "features": [f for f in get(tables["features"]) if f["id"] in feats],
            "organisations": org, "assets": assets}


def check_scope(snap, org_id, products):
    """Everything in the snapshot belongs to the approved scope, or refuse."""
    orgs = snap.get("organisations") or []
    if [o["id"] for o in orgs] != [org_id]:
        refuse("the snapshot holds organisation record(s) %s; the approved scope is %s only"
               % (sorted(o["id"] for o in orgs), org_id))
    org_name = (fv(orgs[0], "Organisation Name") or "").strip()
    if not org_name:
        refuse("the organisation record has no name")
    prods = snap.get("products") or []
    if not prods:
        refuse("the snapshot holds no products")
    for p in prods:
        if link_ids(p, "Organisation") != [org_id]:
            refuse("product %s (%s) is not linked to %s alone; outside the approved scope"
                   % (p["id"], fv(p, "Product Name"), org_name))
    ids = {p["id"] for p in prods}
    if len(ids) != len(prods):
        refuse("the snapshot repeats a product record")
    if products and ids != set(products):
        extra, missing = sorted(ids - set(products)), sorted(set(products) - ids)
        refuse("the snapshot does not match --product: outside scope %s, missing %s"
               % (extra, missing))
    for table in ("pricing", "availability", "featureValues"):
        for r in snap.get(table) or []:
            out = set(link_ids(r, "Product")) - ids
            if out:
                refuse("%s record %s belongs to product(s) %s outside the approved scope"
                       % (table, r["id"], sorted(out)))
    # features are the feature DEFINITIONS (names only); they publish nothing alone.
    for a in snap.get("assets") or []:
        if link_ids(a, "Organisations") != [org_id]:
            refuse("asset %s is not linked to %s alone; outside the approved scope"
                   % (a["id"], org_name))
        if products and not set(link_ids(a, "Products")) <= ids:
            refuse("asset %s is linked to a product outside --product" % a["id"])
    return org_name, ids


