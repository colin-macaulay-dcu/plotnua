def validate(root, wt, moved, rep):
    """The refresh workflow's gates plus the targeted checks. Returns
    [(name, verdict, detail)]; verdict OK / REVIEW / FAIL / PRE-EXISTING."""
    res = []
    py = sys.executable
    cand = pathlib.Path(tempfile.mkdtemp(prefix="tu-cand-"))
    try:
        for f in [GARDEN, DETAIL_EVIDENCE, DETAIL_INDEX] + detail_files(wt):
            shutil.copy(wt / f, cand / f)
        checks = [
            ("validate_garden_room_universe", [py, ".github/scripts/validate_garden_room_universe.py",
                                               "--candidate", str(wt / GARDEN), "--production", str(root / GARDEN)]),
            ("validate_garden_room_detail_evidence", [py, ".github/scripts/validate_garden_room_detail_evidence.py",
                                                      "--candidate", str(cand / DETAIL_EVIDENCE),
                                                      "--production", str(root / DETAIL_EVIDENCE)]),
            ("detail partitions + index", [py, ".github/scripts/validate_garden_room_detail_evidence.py",
                                           "--candidate", str(cand / DETAIL_EVIDENCE), "--index",
                                           str(cand / DETAIL_INDEX), "--partitions-production-dir", str(root)]),
            ("imagery guards (--prove)", [py, IMAGERY, "--prove"]),
            ("image-rights manifest matches records", [py, ".github/scripts/generate_image_rights_manifest.py", "--check"]),
            ("image-rights gate (scan-html)", ["node", "atlas-tools/validate-image-rights.js", "--scan-html", ".",
                                               "--permissions", "image-rights-manifest.json", "--max-age-days", "30"]),
            ("image provenance", ["node", "atlas-tools/validate-image-provenance.js"]),
            ("maker explorer --check", [py, EXPLORER, "--check"]),
            ("search index --check", [py, SEARCH_BUILDER, "--check"]),
            ("maker product links --check", [py, "atlas-tools/verify-maker-product-links.py", "--check"]),
            ("preview-request hold --check", [py, "atlas-tools/apply-preview-request-hold.py", "--check"]),
            ("test_wellness_universe", [py, ".github/scripts/test_wellness_universe.py"]),
            ("prove-atlas-a", ["node", "atlas-tools/prove-atlas-a.mjs"]),
        ]
        for name, cmd in checks:
            script = next((c for c in cmd[1:] if c.endswith((".py", ".js", ".mjs"))), None)
            if script and not (wt / script).exists():
                continue
            if name == "test_wellness_universe" and WELLNESS not in moved:
                continue
            r = sh(cmd, wt)
            if r.returncode == 0:
                res.append((name, "OK", ""))
                continue
            tail = [l for l in (r.stdout + r.stderr).splitlines() if l.strip()][-6:]
            # Failing on the committed state too means it is not ours.
            base_cmd = [c.replace(str(wt / GARDEN), str(root / GARDEN))
                        .replace(str(cand / DETAIL_EVIDENCE), str(root / DETAIL_EVIDENCE))
                        .replace(str(cand / DETAIL_INDEX), str(root / DETAIL_INDEX)) for c in cmd]
            if sh(base_cmd, root).returncode != 0:
                res.append((name, "PRE-EXISTING", " | ".join(tail)[-300:]))
            elif any(c in name for c in CENSUS):
                res.append((name, "REVIEW", " | ".join(tail)[-400:]))
            else:
                res.append((name, "FAIL", " | ".join(tail)[-600:]))
    finally:
        shutil.rmtree(cand, ignore_errors=True)
    return res


