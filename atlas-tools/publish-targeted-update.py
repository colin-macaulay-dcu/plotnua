def refreeze_search(wt, report_name, rep):
    src = (wt / SEARCH_BUILDER).read_text(encoding="utf-8")
    m = re.search(r'^BASE_UNIVERSE_SHA = "([0-9a-f]{64})"', src, re.M)
    if not m:
        refuse("cannot find BASE_UNIVERSE_SHA in the search builder")
    new_sha = sha((wt / GARDEN).read_bytes())
    if m.group(1) == new_sha:
        return
    src = src[:m.start(1)] + new_sha + src[m.end(1):]
    (wt / SEARCH_BUILDER).write_text(src, encoding="utf-8")
    c = (wt / SEARCH_CONTRACT).read_text(encoding="utf-8")
    line = ("- %s · re-frozen to `%s` by atlas-tools/publish-targeted-update.py for a targeted "
            "update (%s); only the targeted records differ.\n"
            % (_dt.date.today().isoformat(), new_sha, report_name))
    head = "## TARGETED-UPDATE RE-FREEZES\n"
    if head not in c:
        c = c.rstrip("\n") + "\n\n---\n\n" + head + "\nThe universe pin above is moved only by a "\
            "targeted publication whose boundary check proved every other record byte-identical.\n\n"
    c = c.rstrip("\n") + "\n" + line
    (wt / SEARCH_CONTRACT).write_text(c, encoding="utf-8")
    rep["search_pin"] = (m.group(1), new_sha)


