def where_published(root, ids):
    """{pid: [files]} over every top-level published artefact."""
    hits = {pid: [] for pid in ids}
    for f in sorted(root.iterdir()):
        if f.suffix not in (".json", ".html", ".js") or not f.is_file():
            continue
        t = f.read_text(encoding="utf-8", errors="replace")
        for pid in ids:
            if pid in t:
                hits[pid].append(f.name)
    return hits


