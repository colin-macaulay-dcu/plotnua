"""
TARGETED SUPPLIER PUBLICATION — ONE ORGANISATION (OR NAMED PRODUCTS), NO
FULL ATLAS REFRESH.

Founder brief "Targeted supplier publication — founder approval to build"
(14 Oct 2026). Replaces supplier-specific publication scripts
(apply-ood-house-targeted-update.py was the template) with one tool that
reuses the existing generators, post-passes, builders and validators.

    DRY RUN  ->  CHANGE REPORT  ->  APPLY  ->  TARGETED VALIDATION
             ->  LOCAL COMMIT  ->  FOUNDER PUSH (by hand, never here)

USAGE
  python3 atlas-tools/publish-targeted-update.py --organisation <rec id> \\
      --snapshot <atlas-read.json> [--product <rec id> ...] [--dry-run]
  ... same arguments ... --apply           write the files (no commit)
  python3 atlas-tools/publish-targeted-update.py --commit
                                           commit exactly what --apply wrote
  --fetch instead of --snapshot reads Atlas with AIRTABLE_TOKEN (read-only).
  --report FILE writes the change report there as well.

WHAT IT DOES
  1. Reads the scoped Atlas records (a snapshot in the Atlas REST shape:
     products, pricing, availability, featureValues, features,
     organisations, optional assets). Everything in it must belong to the
     named organisation and, with --product, to the named products; anything
     else refuses the run.
  2. Finds where every target product is published by scanning the published
     artefacts for its record id, and which Discovery mechanism owns it.
     Supported, because each is regenerated by a per-record generator whose
     header is derivable from its records:
        Garden Rooms (Living in the Garden)   generate_garden_room_universe.py
        Wellness / Sauna (Garden Retreat)     generate_wellness_universe.py
     A product published by any other mechanism (Additional Home, the
     provider universes, the evidence files) refuses the run: those need
     their own regeneration and are a stated limitation, not improvised here.
  3. Runs each generator OFFLINE on the scoped snapshot -- the existing
     eligibility, holds, register, preview list and gate apply unchanged --
     and splices only the target records into the published universe.
     Header counts move only by the targets' own contributions (garden) or
     are re-derived by the generator's own summarise() (wellness); the
     governed digest is recomputed by the generator's own function.
  4. Garden detail partitions, evidence file, supplier entry and index are
     updated for the targets only.
  5. Authorised imagery: the organisation's Atlas Asset records (if the
     snapshot carries them) replace its rows in approved-image-assets-v1.json;
     apply_authorised_imagery.py then decides every image exactly as before
     (live grant, scoped prefix, product link, credit, photographer,
     link-back, photograph vs visualisation).
  6. Maker Explorers and Search are rebuilt by their own builders; the
     search contract's universe pin is re-frozen deliberately and logged.
  7. BOUNDARY CHECK: only managed files may change; every non-target record,
     detail entry, supplier entry, search record and explorer maker must be
     byte-identical. Anything else refuses.
  8. Validators: the refresh workflow's own gates plus the imagery, rights,
     explorer, search, link and preview-hold checks.

  It never pushes, deploys, emails, writes to Atlas, or grants anything.
  New products (not yet published anywhere) publish only when named with
  --product; under an organisation-wide run they are reported and left out.
"""
