def garden_contribution(rec):
    """What one record contributes to the header counts that cover EMITTED
    AND EXCLUDED products. Emitted-only counts are recomputed from the list."""
    q = rec["qualification"]
    s = q["evidenceSignals"]
    c = {"sourceGardenRoomCount": 1,
         "excludedCount": 1 if q["hardBlockers"] else 0,
         "unclassifiedIrishAvailabilityCount": 0 if s.get("irishAvailabilityClassified") else 1,
         "noPublishedIrishRouteCount": 1 if s.get("noPublishedIrishRoute") else 0,
         "missingProductUrlCount": 0 if rec.get("productUrl") else 1}
    ie = {"confirmed": "confirmedIrishAvailabilityCount",
          "unknown": "unknownIrishAvailabilityCount",
          "unavailable": "confirmedUnavailableCount"}.get(s.get("irishAvailability"))
    if ie:
        c[ie] = 1
    for b in q["hardBlockers"]:
        c["E:" + b["code"]] = c.get("E:" + b["code"], 0) + 1
    return c


def garden_emitted_header(products, g):
    tiers = {t: sum(1 for e in products if e["qualification"]["confidenceTier"] == t)
             for t in ("HIGH_CONFIDENCE", "WITH_CAVEAT", "LIMITED_EVIDENCE")}
    pa = {s: sum(1 for e in products if e["qualification"]["evidenceSignals"]["price"] == s)
          for s in ("verified", "present-unverified", "quote-only", "missing")}
    return {"eligibleCount": len(products),
            "highConfidenceCount": tiers["HIGH_CONFIDENCE"],
            "withCaveatCount": tiers["WITH_CAVEAT"],
            "limitedEvidenceCount": tiers["LIMITED_EVIDENCE"],
            "missingPriceCount": pa["missing"], "priceEvidenceSummary": pa,
            "quoteOnlyPriceCount": pa["quote-only"],
            "organisationCount": len({e.get("organisation") for e in products if e.get("organisation")}),
            "governedDigest": g.governed_digest(products)}


def garden_adapter(wt, snap_path, snap, targets, explicit, org_id, rep):
    g = load_module(wt / GARDEN_GEN, "grgen_targeted")
    cur_raw = (wt / GARDEN).read_text(encoding="utf-8")
    cur = json.loads(cur_raw)
    if cur.get("qualificationRuleVersion") != g.RULE_VERSION:
        refuse("the garden generator's rule (%s) is not the one the published universe was "
               "built with (%s); that needs a full refresh" % (g.RULE_VERSION, cur.get("qualificationRuleVersion")))
    if cur.get("governedPriceContractVersion") != g.GOVERNED_CONTRACT_VERSION:
        refuse("the governed price contract changed since the last refresh; full refresh needed")
    base_hdr = garden_emitted_header(cur["products"], g)
    for k, v in base_hdr.items():
        if cur.get(k) != v:
            refuse("the published garden universe header is inconsistent (%s); fix that first" % k)

    old = {p["productId"]: p for p in cur["products"] if p["productId"] in targets}
    out = pathlib.Path(tempfile.mkdtemp(prefix="tu-garden-"))
    try:
        if not any(fv(p, "Product Category") == g.GARDEN_ROOMS for p in snap["products"]):
            new_em, new_ex, gen_files = {}, {}, {}
        else:
            r = sh([sys.executable, str(wt / GARDEN_GEN), "--snapshot", str(snap_path),
                    "--out-dir", str(out), "--production-candidate"], wt)
            if r.returncode:
                refuse("the garden generator refused the snapshot:\n" + (r.stdout + r.stderr)[-2500:])
            gen_files = {p.name: json.loads(p.read_text(encoding="utf-8")) for p in out.glob("*.json")}
            new_em = {p["productId"]: p for p in gen_files[GARDEN]["products"]}
            new_ex = {p["productId"]: p for p in
                      gen_files["garden-room-exclusions-v1.json"]["excluded"]}
    finally:
        shutil.rmtree(out, ignore_errors=True)

    published_at = cur["generated"]
    created = {p["id"]: p.get("createdTime") or "" for p in snap["products"]}
    keep_new, skipped = {}, []
    delta = {}

    def add(c, sign):
        for k, v in c.items():
            delta[k] = delta.get(k, 0) + sign * v

    for pid in sorted(targets):
        if pid in old:
            add(garden_contribution(old[pid]), -1)
            nr = new_em.get(pid) or new_ex.get(pid)
            if nr:
                add(garden_contribution(nr), +1)
            if pid in new_em:
                keep_new[pid] = new_em[pid]
        elif pid in new_em:
            if pid not in explicit:
                skipped.append((pid, new_em[pid]["name"], "new to Living in the Garden; "
                                "publish only by naming it with --product after review"))
                continue
            if not created.get(pid) or created[pid] <= published_at:
                refuse("%s (%s) is eligible but unpublished and predates the last refresh "
                       "(%s): whether the refresh counted it as excluded cannot be known, so "
                       "the header cannot be moved exactly. Needs a full refresh."
                       % (pid, new_em[pid]["name"], published_at))
            add(garden_contribution(new_em[pid]), +1)
            keep_new[pid] = new_em[pid]
        elif pid in new_ex:
            skipped.append((pid, new_ex[pid]["name"], "not published and still excluded (%s)"
                            % ", ".join(b["code"] for b in new_ex[pid]["qualification"]["hardBlockers"])))
    changed_any = bool(old) or bool(keep_new)
    if not changed_any:
        return None, skipped

    products = [p for p in cur["products"] if p["productId"] not in targets]
    for pid, n in keep_new.items():
        n = copy.deepcopy(n)
        n.pop("imagery", None)
        n.pop("imagerySet", None)
        # the imagery pass re-decides imagery; carry the old block so an
        # unchanged product stays byte-identical before that pass runs
        if pid in old:
            for k in ("imagery", "imagerySet"):
                if k in old[pid]:
                    n[k] = old[pid][k]
        products.append(n)
    products.sort(key=lambda p: (p["name"], p["productId"]))

    new = copy.deepcopy(cur)
    new["products"] = products
    for k, v in delta.items():
        if k.startswith("E:"):
            s = new["exclusionSummaryByReason"]
            s[k[2:]] = s.get(k[2:], 0) + v
            if s[k[2:]] < 0:
                refuse("exclusion count %s would go negative" % k[2:])
            if s[k[2:]] == 0:
                del s[k[2:]]
        else:
            new[k] += v
            if new[k] < 0:
                refuse("header count %s would go negative" % k)
    new.update(garden_emitted_header(products, g))
    if new["sourceGardenRoomCount"] != new["eligibleCount"] + new["excludedCount"]:
        refuse("source count %d != eligible %d + excluded %d after the splice"
               % (new["sourceGardenRoomCount"], new["eligibleCount"], new["excludedCount"]))
    (wt / GARDEN).write_text(dump1(new), encoding="utf-8")
    rep["garden"] = {"old": old, "new": keep_new, "header_before": {k: v for k, v in cur.items() if k != "products"},
                     "header_after": {k: v for k, v in new.items() if k != "products"}}

    # ---- detail partitions, evidence file, supplier entry, index ----------
    final_order = [p["productId"] for p in products]
    emitted_ids = set(final_order)
    idx = json.loads((wt / DETAIL_INDEX).read_text(encoding="utf-8"))
    declared = {p["file"] for p in idx["partitions"]}
    for name in gen_files:
        if name.startswith("garden-room-detail-") and name not in declared \
                and name not in (DETAIL_EVIDENCE, DETAIL_INDEX):
            refuse("the generator wrote a detail partition the index does not declare (%s); "
                   "a new category needs a full refresh" % name)
    detail_changes = []

    def rebuild(doc, newdoc, cats):
        prods = doc["products"]
        add_from = (newdoc or {}).get("products") or {}
        for pid in targets:
            if pid in prods:
                del prods[pid]
            if pid in add_from and pid in emitted_ids:
                prods[pid] = add_from[pid]
        doc["products"] = {pid: prods[pid] for pid in final_order if pid in prods}
        stray = set(prods) - set(doc["products"])
        if stray:
            refuse("detail entries for unpublished products %s" % sorted(stray)[:5])
        doc["productCount"] = len(doc["products"])
        if "recordCounts" in doc:
            doc["recordCounts"] = {k: sum(len(v[k].get("records", [None]))
                                          for v in doc["products"].values() if k in v)
                                   for k in cats}

    for part in idx["partitions"]:
        f = wt / part["file"]
        old_text = f.read_text(encoding="utf-8")
        d = json.loads(old_text)
        if part["category"] == "suppliers":
            nd = (gen_files.get(part["file"]) or {}).get("products") or {}
            if org_id in nd:
                if d["products"].get(org_id) != nd[org_id]:
                    detail_changes.append(("suppliers", org_id))
                    rep.setdefault("supplier", (d["products"].get(org_id), nd[org_id]))
                    if org_id in d["products"]:
                        d["products"][org_id] = nd[org_id]
                    else:
                        d["products"][org_id] = nd[org_id]
                d["productCount"] = len(d["products"])
            elif org_id in d["products"]:
                rep.setdefault("notes", []).append(
                    "Supplier entry kept unchanged: the snapshot holds no garden-room product "
                    "for this organisation, so whether it should go cannot be decided here.")
            part["recordCount"] = sum(len(v["locality"]) for v in d["products"].values())
        else:
            rebuild(d, gen_files.get(part["file"]), d["categories"])
            part["recordCount"] = d["recordCounts"][part["category"]]
        part["productCount"] = len(d["products"])
        text = dump2(d)
        if text != old_text:
            part["rawBytes"] += len(text.encode("utf-8")) - len(old_text.encode("utf-8"))
            f.write_text(text, encoding="utf-8")
            if part["category"] != "suppliers":
                detail_changes.append((part["category"], None))
    ev_text = (wt / DETAIL_EVIDENCE).read_text(encoding="utf-8")
    ev = json.loads(ev_text)
    rebuild(ev, gen_files.get(DETAIL_EVIDENCE), ev["categories"])
    if dump2(ev) != ev_text:
        (wt / DETAIL_EVIDENCE).write_text(dump2(ev), encoding="utf-8")
    idx_text = dump2(idx)
    if idx_text != (wt / DETAIL_INDEX).read_text(encoding="utf-8"):
        (wt / DETAIL_INDEX).write_text(idx_text, encoding="utf-8")
    rep["garden"]["detail"] = sorted({c for c, _ in detail_changes})
    return True, skipped


