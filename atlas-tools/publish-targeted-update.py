def explorer_config(text):
    m = re.search(r'(<script type="application/json" class="pn-mx-config" id="mx-data">)(.*?)(</script>)',
                  text, re.S)
    return (json.loads(m.group(2)), m) if m else (None, None)


def boundary(root, wt, targets, org_names, rep):
    """Only managed files move, and inside them only the targets."""
    allowed = managed_files(root)
    st = sh(["git", "status", "--porcelain", "--untracked-files=all"], wt, check=True).stdout
    moved = sorted({l[3:].strip() for l in st.splitlines() if l.strip()})
    stray = [f for f in moved if f not in allowed]
    if stray:
        refuse("files outside the targeted-publication set would change: %s" % stray)
    head = lambda f: (root / f).read_text(encoding="utf-8") if (root / f).exists() else None

    def same_except(a_list, b_list, key, label):
        a = {key(x): jkey(x) for x in a_list}
        b = {key(x): jkey(x) for x in b_list}
        for k in set(a) | set(b):
            if k in targets:
                continue
            if a.get(k) != b.get(k):
                refuse("%s record %s outside the scope would change" % (label, k))

    if GARDEN in moved:
        a, b = json.loads(head(GARDEN)), json.loads((wt / GARDEN).read_text(encoding="utf-8"))
        same_except(a["products"], b["products"], lambda p: p["productId"], "garden-room")
    if WELLNESS in moved:
        a, b = json.loads(head(WELLNESS)), json.loads((wt / WELLNESS).read_text(encoding="utf-8"))
        same_except(a["products"], b["products"], lambda p: p["id"], "wellness")
    for f in detail_files(root) + [DETAIL_EVIDENCE]:
        if f not in moved:
            continue
        a = json.loads(head(f))["products"]
        b = json.loads((wt / f).read_text(encoding="utf-8"))["products"]
        org_ids = rep.get("org_id")
        for k in set(a) | set(b):
            if k in targets or k == org_ids:
                continue
            if jkey(a.get(k)) != jkey(b.get(k)):
                refuse("%s entry %s outside the scope would change" % (f, k))
    if SEARCH in moved:
        a, b = json.loads(head(SEARCH)), json.loads((wt / SEARCH).read_text(encoding="utf-8"))
        def skey(r):
            return (r.get("type"), r.get("id"))
        ra = {skey(r): r for r in a["records"]}
        rb = {skey(r): r for r in b["records"]}
        for k in set(ra) | set(rb):
            if k[0] == "product" and str(k[1]).split("-", 1)[-1] in targets:
                continue
            if k[0] == "supplier" and any((x or {}).get("name") in org_names
                                          for x in (ra.get(k), rb.get(k))):
                continue
            if jkey(ra.get(k)) != jkey(rb.get(k)):
                refuse("search record %s outside the scope would change" % (k,))
        rep["search_counts"] = (a.get("counts"), b.get("counts"))
    for page in explorer_pages(root):
        if page not in moved:
            continue
        ta, tb = head(page), (wt / page).read_text(encoding="utf-8")
        ca, ma = explorer_config(ta)
        cb, mb = explorer_config(tb)
        if ca is None or cb is None:
            refuse("%s: maker explorer config not found" % page)
        for tab_a, tab_b in zip(ca["tabs"], cb["tabs"]):
            if tab_a.get("key") != tab_b.get("key"):
                refuse("%s: explorer tabs changed" % page)
            ma_ = {x["m"]: x for x in tab_a.get("makers", [])}
            mb_ = {x["m"]: x for x in tab_b.get("makers", [])}
            for name in set(ma_) | set(mb_):
                if name in org_names:
                    continue
                if jkey(ma_.get(name)) != jkey(mb_.get(name)):
                    refuse("%s: maker %s outside the scope would change" % (page, name))
            ra_ = {k: v for k, v in tab_a.items() if k not in ("makers", "figures")}
            rb_ = {k: v for k, v in tab_b.items() if k not in ("makers", "figures")}
            if jkey(ra_) != jkey(rb_):
                refuse("%s: explorer tab settings changed" % page)
            if tab_a.get("figures") != tab_b.get("figures"):
                rep.setdefault("explorer_figures", []).append(
                    (page, tab_a.get("key"), tab_a.get("figures"), tab_b.get("figures")))
        rest_a = (ta[:ma.start(2)] + ta[ma.end(2):])
        rest_b = (tb[:mb.start(2)] + tb[mb.end(2):])
        if re.sub(r"\d+", "#", rest_a) != re.sub(r"\d+", "#", rest_b):
            refuse("%s: page text outside the explorer figures would change" % page)
    return moved


