def update_assets(wt, snap, org_id, org_name, rep, products=None):
    if "assets" not in snap:
        rep["assets"] = "snapshot carries no Asset records; approved-image-assets-v1.json unchanged"
        return
    img = load_module(wt / IMAGERY, "img_targeted")
    if not hasattr(img, "atlas_asset_rows"):
        refuse("this checkout's imagery pass cannot read Atlas Asset records")
    if org_name in {a["organisation"] for a in img.HAND_ASSETS}:
        refuse("%s's imagery is in apply_authorised_imagery.py's hand list; move it to "
               "approved-image-assets-v1.json before updating it from Atlas" % org_name)
    f = wt / ASSETS
    doc = json.loads(f.read_text(encoding="utf-8")) if f.exists() else {
        "schema": "plotnua.approved-image-assets.v1", "what_this_is": ASSETS_WHAT,
        "organisations": {}, "records": []}
    # With --product only the named products' assets are in scope; the rest
    # of the organisation's assets are kept exactly as they are.
    def mine(r):
        return link_ids(r, "Organisations") == [org_id] and (
            not products or set(link_ids(r, "Products")) <= products)
    before = [r for r in doc["records"] if mine(r)]
    keep = [r for r in doc["records"] if not mine(r)]
    rows = []
    for a in snap["assets"]:
        r = {"id": a["id"]}
        if a.get("createdTime"):
            r["createdTime"] = a["createdTime"]
        r["fields"] = a["fields"]
        rows.append(r)
    refused = []
    img.atlas_asset_rows({"records": rows}, refused)
    rep["assets"] = {"before": len(before), "after": len(rows), "refused": refused}
    same = [jkey(x) for x in sorted(before, key=lambda r: r["id"])] == \
        [jkey(x) for x in sorted(rows, key=lambda r: r["id"])]
    if same and f.exists():
        return
    doc["records"] = sorted(keep + rows, key=lambda r: r["id"])
    doc.setdefault("organisations", {})[org_id] = {
        "name": org_name, "read": _dt.date.today().isoformat(),
        "filter": "Assets.Organisations contains %s" % org_name}
    if not rows:
        del doc["organisations"][org_id]
    f.write_text(dump1(doc), encoding="utf-8")


