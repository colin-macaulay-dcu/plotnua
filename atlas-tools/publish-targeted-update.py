def git_root(p):
    return pathlib.Path(sh(["git", "rev-parse", "--show-toplevel"], p, check=True).stdout.strip())


def run(a):
    root = git_root(pathlib.Path(a.root).resolve() if a.root else SELF_ROOT)
    dirty = sh(["git", "status", "--porcelain", "--untracked-files=no"], root, check=True).stdout.strip()
    if dirty:
        refuse("the working tree has uncommitted changes; a targeted update starts from a clean "
               "commit:\n" + dirty)
    head_sha = sh(["git", "rev-parse", "HEAD"], root, check=True).stdout.strip()
    if a.fetch:
        snap = fetch_snapshot(a.organisation, a.product)
        tmp_snap = pathlib.Path(tempfile.mkdtemp(prefix="tu-snap-")) / "snapshot.json"
        tmp_snap.write_text(json.dumps(snap, ensure_ascii=False, indent=1), encoding="utf-8")
        snap_path = tmp_snap
    else:
        snap_path = pathlib.Path(a.snapshot).resolve()
        snap = json.loads(snap_path.read_text(encoding="utf-8"))
    snap_sha = sha(snap_path.read_bytes())
    org_name, targets = check_scope(snap, a.organisation, a.product)
    explicit = set(a.product or ())
    rep = {"org_id": a.organisation, "snap_source": snap.get("source")}

    # where is each target published, and by what
    hits = where_published(root, targets)
    managed = managed_files(root)
    for pid, files in hits.items():
        other = [f for f in files if f not in managed and f not in SEPARATE]
        if other:
            refuse("%s is published by a mechanism this tool does not manage (%s); that "
                   "Discovery needs its own regeneration" % (pid, ", ".join(other)))
    # org-wide: every published product of the organisation must be in the read
    if not a.product:
        for f, key, orgk in ((GARDEN, "productId", "organisation"), (WELLNESS, "id", "organisation")):
            if (root / f).exists():
                for p in json.loads((root / f).read_text(encoding="utf-8"))["products"]:
                    if p.get(orgk) == org_name and p[key] not in targets:
                        refuse("%s (%s) is published for %s but missing from the Atlas read; an "
                               "organisation-wide update needs all of them" % (p[key], f, org_name))

    wt = pathlib.Path(tempfile.mkdtemp(prefix="tu-wt-")) / "wt"
    sh(["git", "worktree", "add", "--detach", str(wt), "HEAD"], root, check=True)
    try:
        g_changed, sk1 = garden_adapter(wt, snap_path, snap, targets, explicit, a.organisation, rep) \
            if (wt / GARDEN).exists() else (None, [])
        w_changed, sk2 = wellness_adapter(wt, snap_path, snap, targets, explicit, org_name, rep, snap_sha) \
            if (wt / WELLNESS).exists() else (None, [])
        update_assets(wt, snap, a.organisation, org_name, rep, set(a.product or ()))
        stamp = _dt.datetime.now(_dt.timezone.utc).strftime("%Y%m%d-%H%M%S")
        slug = re.sub(r"[^a-z0-9]+", "-", unicodedata.normalize("NFKD", org_name.lower())
                      .encode("ascii", "ignore").decode()).strip("-") or a.organisation.lower()
        report_name = "%s/%s-%s.md" % (REPORT_DIR, stamp, slug)
        run_imagery(wt, rep)
        refreeze_search(wt, report_name, rep)
        run_builders(wt, rep)
        org_names = {org_name}
        moved = boundary(root, wt, targets, org_names, rep)
        results = None if a.no_validate else validate(root, wt, moved, rep)
        text = render_report(a, rep, org_name, targets, moved, results, sk1 + sk2, hits, snap_sha, head_sha)
        failed = [r for r in results or [] if r[1] == "FAIL"]
        print(text)
        if a.report:
            pathlib.Path(a.report).write_text(text, encoding="utf-8")
        if failed:
            refuse("validation failed: " + ", ".join(r[0] for r in failed))
        if not moved:
            print("NOTHING TO PUBLISH — the published files already match Atlas for this scope.")
            return 0
        if not a.apply:
            print("DRY RUN — nothing written. Re-run with --apply to write these files.")
            return 0
        for f in moved:
            dst = root / f
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(wt / f, dst)
        (root / report_name).parent.mkdir(parents=True, exist_ok=True)
        (root / report_name).write_text(text, encoding="utf-8")
        gitdir = pathlib.Path(sh(["git", "rev-parse", "--absolute-git-dir"], root, check=True).stdout.strip())
        (gitdir / LAST).write_text(json.dumps({
            "head": head_sha, "organisation": a.organisation, "organisationName": org_name,
            "products": sorted(targets), "files": moved + [report_name],
            "fingerprints": {f: sha((root / f).read_bytes()) for f in moved + [report_name]},
            "review": [r[0] for r in results or [] if r[1] == "REVIEW"],
        }, indent=1), encoding="utf-8")
        print("APPLIED — %d file(s) written; report %s. Nothing committed or pushed.\n"
              "Next: review, then  python3 atlas-tools/publish-targeted-update.py --commit"
              % (len(moved), report_name))
        return 0
    finally:
        sh(["git", "worktree", "remove", "--force", str(wt)], root)
        shutil.rmtree(wt.parent, ignore_errors=True)


def commit(a):
    root = git_root(pathlib.Path(a.root).resolve() if a.root else SELF_ROOT)
    gitdir = pathlib.Path(sh(["git", "rev-parse", "--absolute-git-dir"], root, check=True).stdout.strip())
    if not (gitdir / LAST).exists():
        refuse("no applied targeted update to commit")
    m = json.loads((gitdir / LAST).read_text(encoding="utf-8"))
    if sh(["git", "rev-parse", "HEAD"], root, check=True).stdout.strip() != m["head"]:
        refuse("HEAD moved since --apply; re-run the update")
    st = sh(["git", "status", "--porcelain", "--untracked-files=all"], root, check=True).stdout
    moved = sorted({l[3:].strip() for l in st.splitlines() if l.strip()})
    if set(moved) != set(m["files"]):
        refuse("the working tree differs from what --apply wrote: extra %s, missing %s"
               % (sorted(set(moved) - set(m["files"])), sorted(set(m["files"]) - set(moved))))
    for f, h in m["fingerprints"].items():
        if sha((root / f).read_bytes()) != h:
            refuse("%s was edited after --apply" % f)
    if m["review"] and not a.accept_review:
        refuse("census pins need review first (%s): update them deliberately, commit that "
               "separately, or pass --accept-review" % ", ".join(m["review"]))
    sh(["git", "add", "--"] + m["files"], root, check=True)
    msg = ("Targeted update: %s (%d product record(s))\n\n"
           "Published with atlas-tools/publish-targeted-update.py from a scoped Atlas read; "
           "only these records moved. Report: %s\n\n%s\n"
           % (m["organisationName"], len(m["products"]), m["files"][-1], TRAILERS))
    env = dict(os.environ, GIT_AUTHOR_NAME="Colin MacAulay", GIT_AUTHOR_EMAIL="kolin.macaulay@gmail.com",
               GIT_COMMITTER_NAME="Colin MacAulay", GIT_COMMITTER_EMAIL="kolin.macaulay@gmail.com")
    sh(["git", "commit", "-q", "-m", msg], root, check=True, env=env)
    (gitdir / LAST).unlink()
    print("COMMITTED %s locally. Not pushed." %
          sh(["git", "rev-parse", "--short", "HEAD"], root, check=True).stdout.strip())
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description="Targeted supplier publication (no full refresh).")
    ap.add_argument("--organisation")
    ap.add_argument("--product", action="append")
    src = ap.add_mutually_exclusive_group()
    src.add_argument("--snapshot")
    src.add_argument("--fetch", action="store_true")
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true")
    mode.add_argument("--apply", action="store_true")
    mode.add_argument("--commit", action="store_true")
    ap.add_argument("--accept-review", action="store_true")
    ap.add_argument("--report")
    ap.add_argument("--root", help="repository to act on (default: this tool's own)")
    ap.add_argument("--no-validate", action="store_true", help=argparse.SUPPRESS)
    a = ap.parse_args(argv)
    try:
        if a.commit:
            return commit(a)
        if not a.organisation or not (a.snapshot or a.fetch):
            ap.error("--organisation and --snapshot (or --fetch) are required")
        return run(a)
    except Refused as e:
        print("REFUSED: %s" % e)
        return 2


if __name__ == "__main__":
    sys.exit(main())
