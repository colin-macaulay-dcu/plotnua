def sh(cmd, cwd, check=False, env=None):
    r = subprocess.run(cmd, cwd=str(cwd), capture_output=True, text=True, env=env)
    if check and r.returncode:
        refuse("%s failed:\n%s%s" % (" ".join(map(str, cmd)), r.stdout[-2000:], r.stderr[-2000:]))
    return r


def sha(b):
    return hashlib.sha256(b if isinstance(b, bytes) else b.encode("utf-8")).hexdigest()


def load_module(path, name):
    d = str(pathlib.Path(path).parent)
    if d not in sys.path:
        sys.path.insert(0, d)
    spec = importlib.util.spec_from_file_location(name, path)
    m = importlib.util.module_from_spec(spec)
    argv, sys.argv = sys.argv, [str(path)]
    try:
        spec.loader.exec_module(m)
    finally:
        sys.argv = argv
    return m


def fv(rec, name):
    return (rec.get("fields") or {}).get(name)


def link_ids(rec, name):
    v = fv(rec, name) or []
    if isinstance(v, str):
        v = [v]
    return [x["id"] if isinstance(x, dict) else x for x in v]


