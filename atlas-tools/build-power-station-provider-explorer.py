def strip(html):
    """Remove everything this builder adds and revert the correction."""
    html = re.sub(r"\n?" + re.escape(BEGIN) + r"[\s\S]*?" + re.escape(END), "", html)
    html = html.replace(STYLE_END + "\n" + CSS_LINK, STYLE_END)
    for _, old, new in CORRECTIONS:
        html = html.replace(new, old)
    return html


def build(current):
    u = json.loads(UNIVERSE.read_text(encoding="utf-8"))
    html = strip(current)
    for label, old, new in CORRECTIONS:
        if html.count(old) != 1:
            die("P10 correction anchor not found exactly once: " + label)
        html = html.replace(old, new)
    if html.count(STYLE_END) != 1:
        die("P12 head style end marker not found exactly once")
    html = html.replace(STYLE_END, STYLE_END + "\n" + CSS_LINK)
    if html.count(ANCHOR) != 1:
        die("P8 placement anchor (end of 'The energy anatomy of your property') not found exactly once")
    html = html.replace(ANCHOR, ANCHOR + "\n" + section(u))
    return html, u


def guards(html, u):
    # P1
    r = subprocess.run([sys.executable, str(UBUILD), "--check"], capture_output=True, text=True)
    if r.returncode != 0:
        die("P1 the provider universe is not up to date or fails its own guards:\n" + r.stdout + r.stderr)
    # P2
    for f, pin in PINS.items():
        if sha(f) != pin:
            die("P2 %s does not match its pin (%s)" % (f, sha(f)))
    # P3
    code = strip_offlink(re.sub(r"/\*[\s\S]*?\*/", "", (ROOT / "provider-explorer.js").read_text(encoding="utf-8")))
    for bad in FORBIDDEN_JS:
        if bad in code:
            die("P3 provider-explorer.js contains %r" % bad)
    # P4
    a = html.index(BEGIN); b = html.index(END)
    sec = html[a:b]
    visible = sec.replace('src="provider-explorer.js"', "")
    # The official links (14 Oct 2026) live in the config only, one per
    # supplier, each already proved by the universe builder's W6. They are
    # the only "http" the section may hold; anything else still refuses.
    # A link the universe withheld (stale or failed check) simply is not there;
    # the supplier stays listed.
    links = [o["link"] for t in u["tabs"] for o in t["orgs"] if "link" in o]
    if len(links) > len(SUPPLIERS) or any(set(L) != {"href", "label"} for L in links):
        die("P4 a supplier carries more than one official link, or a malformed one")
    for L in links:
        frag = '"href":%s' % json.dumps(L["href"], ensure_ascii=False, separators=(",", ":"))
        if visible.count(frag) != 1:
            die("P4 an official link is not in the configuration exactly once: %s" % L["href"])
        visible = visible.replace(frag, "")
    for bad in ("<a ", "href=", "<form", "<input", "<iframe", "http"):
        if bad in visible:
            die("P4 the explorer section contains %r" % bad)
    body = re.sub(r"<!--[\s\S]*?-->", "", visible)
    body = re.sub(r'"(evidence|evidenceOldest)":"[^"]*"', "", body)
    if MONEY.search(body):
        die("P4 money, rate or earnings wording in the explorer: %r" % MONEY.search(body).group(0))
    body = body.replace('<span class="mx-n">%d</span>' % len(SUPPLIERS), "")  # the tab's count badge
    if re.search(r"\d", re.sub(r'(id|class|aria-[a-z]+|data-[a-z]+)="[^"]*"|NC6|ORG-ESUP-[A-Z]+|<h2|</h2>|"code":"[^"]*"', "", body)):
        die("P4 a numeral appears in the explorer's visible text")
    base = strip(html)
    if len(re.findall(r'href="https?://', html)) != len(re.findall(r'href="https?://', base)):
        die("P4 the page gained an external link")
    # P5
    if u["partnersCount"] != 0:
        die("P5 partnersCount is not 0")
    for t in u["tabs"]:
        for o in t["orgs"]:
            if o.get("partner") is not False:
                die("P5 %s is not partner:false" % o["code"])
    if sec.count(STATEMENT) != 1:
        die("P5 the single researched-not-partners statement is missing or repeated")
    if re.search(r"\bpartner(ed|ship)? with\b|PlotNua partner\b(?!s\.)|\bfeatured\b|\brecommended\b", sec, re.I):
        die("P5 partnership or endorsement wording in the explorer")
    # P6
    if [t["label"] for t in u["tabs"]] != ["Electricity suppliers"]:
        die("P6 tabs are %r" % [t["label"] for t in u["tabs"]])
    if [o["name"] for o in u["tabs"][0]["orgs"]] != SUPPLIERS:
        die("P6 suppliers are not exactly the four DISC-026 pilot suppliers, A to Z")
    # P7
    m = re.search(r'<script type="application/json" class="pn-px-config" id="px-data">([\s\S]*?)</script>', sec)
    if not m or json.loads(m.group(1).replace("<\\/", "</")) != {"tabs": u["tabs"]}:
        die("P7 the embedded configuration does not equal the universe")
    # P8
    # The Property Check HANDOFF is the last Property Check link on the page.
    # Since 15 Oct 2026 the founder-approved "Look again at your house" section
    # (build-disc026-look-again.py) adds a second route near the top, so the
    # handoff is found with rfind, not find.
    marks = [html.find(s) for s in ("<h2>The energy anatomy of your property</h2>", 'id="explore-providers"',
                                     "CONCEPT IMAGERY, position 1 of 2")] + [html.rfind(PC_LINK)]
    if -1 in marks or not (marks[0] < marks[1] < marks[2] < marks[3]):
        die("P8 explorer is not between the energy anatomy and the S8 imagery, ahead of the Property Check")
    if not html[b + len(END):].lstrip().startswith("</div>"):
        die("P8 explorer is not inside the article wrapper")
    for link in (PC_LINK, CR_LINK):
        if html.count(link) != base.count(link) or html.count(link) < 1:
            die("P8 a check link changed: " + link)
    # P9
    try:
        head = subprocess.run(["git", "-C", str(ROOT), "show", "HEAD:" + PAGE_NAME],
                              capture_output=True, text=True, check=True).stdout
        if strip(head) != base:
            die("P9 the rest of the page differs from git HEAD beyond the explorer, its link and the correction")
    except (subprocess.CalledProcessError, FileNotFoundError):
        print("  P9 skipped: git HEAD not available")
    # P10
    for label, old, new in CORRECTIONS:
        if html.count(new) != 1 or old in html:
            die("P10 correction not applied cleanly: " + label)
    for c in COMPUTE_CAVEATS:
        if html.count(c) != 1:
            die("P10 a computing caveat changed: " + c[:60])
    # P11
    for t in TOKENS:
        if t + ":" not in html:
            die("P11 host page does not define " + t)
    # P12
    if html.count(CSS_LINK) != 1 or html.index(CSS_LINK) > html.index("</head>"):
        die("P12 stylesheet link missing, duplicated or outside <head>")
    if html.count('class="pn-px-config"') != 1 or html.count('<script src="provider-explorer.js"></script>') != 1:
        die("P12 config or script missing or duplicated")
    if "data-pn-maker-explorer" in html:
        die("P12 the Maker Explorer must not be on this page")


def main(argv):
    if "--apply" not in argv and "--check" not in argv:
        print(__doc__); sys.exit(1)
    current = PAGE.read_text(encoding="utf-8")
    html, u = build(current)
    guards(html, u)
    n = sum(len(t["orgs"]) for t in u["tabs"])
    summary = "%d suppliers in %d tab" % (n, len(u["tabs"]))
    if "--check" in argv:
        if html != current:
            print("CHECK FAILED: %s is out of date; run --apply" % PAGE_NAME); sys.exit(1)
        print("%s: %s · CHECK OK — P1-P12 pass" % (PAGE_NAME, summary)); return
    PAGE.write_text(html, encoding="utf-8")
    print("%s: %s · APPLIED — P1-P12 pass" % (PAGE_NAME, summary))


if __name__ == "__main__":
    main(sys.argv[1:])
