#!/usr/bin/env python3
"""PLOTNUA · Garden Saunas in Ireland guide — comparison builder and guard (founder instruction, 12 Nov 2026).

Generates the static maker comparison on garden-saunas-ireland.html from the dated, sourced evidence file
atlas-tools/garden-saunas-guide/evidence-2026-11-12.json (a read-only recheck of each maker's own pages).
Nothing here reads or writes Atlas, permissions or publication state.

Guards (every run; --check also refuses a stale generated region):
  S1 eligible makers: every maker in the evidence is publicly listed in Garden Retreat's sauna Maker Explorer
     (independent source: discovery-garden-retreat.html #mx-data) or is a declared bespoke-only maker with a
     public PlotNua profile; every publicly listed sauna maker except the declared exclusions is covered.
  S2 exclusions: TimberIN (founder, 12 Nov 2026: until Republic of Ireland delivery is verified) and every
     preview-only or held organisation are absent from the whole page, as are private preview links.
  S3 links: every internal profile resolves to a public, indexable page in the sitemap; every product source
     is on the maker's own host; no outbound link carries tracking parameters.
  S4 facts: every product has a source URL, a price text, a price basis and a VAT statement; a missing
     dimension, capacity or heater is printed as "Not stated by the maker", never left blank.
  S5 money: every euro figure on the page appears in the evidence (no stray or invented price).
  S6 imagery: the page carries no images other than PlotNua's own brand assets.
  S7 freshness: the evidence is no older than 30 days, and no introductory price is shown after its end date.
  S8 disclosure: "PlotNua has no commercial arrangement with any maker listed here" is present and no listed
     maker has an ACTIVE entry in atlas-tools/commercial-arrangements-register.json.
  S9 parent: the first link in <main> goes to Garden Retreat; the hero states the number of makers compared.

  python3 atlas-tools/build-garden-saunas-guide.py            build the region, then run the guards
  python3 atlas-tools/build-garden-saunas-guide.py --check    guards + region up to date (no write)
  python3 atlas-tools/build-garden-saunas-guide.py --prove    mutation proof: every guard must refuse
"""
import datetime as dt, hashlib, html as H, json, os, re, sys
from urllib.parse import urlparse

ROOT = os.environ.get("PN_ROOT") or os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAGE = "garden-saunas-ireland.html"
EVIDENCE = os.path.join("atlas-tools", "garden-saunas-guide", "evidence-2026-11-12.json")
RETREAT = "discovery-garden-retreat.html"
BEGIN = ("<!-- GARDEN SAUNAS GUIDE · COMPARISON · BEGIN · generated by atlas-tools/build-garden-saunas-guide.py"
         " — do not hand-edit -->")
END = "<!-- GARDEN SAUNAS GUIDE · COMPARISON · END -->"
# Atlas organisation name -> the name the guide uses (the explorer is the independent source of eligibility).
ALIAS = {"Gardenhouse24 Ireland": "Gardenhouse24", "Hansa24 Group": "Summerhouse24 (Hansa24 Group)"}
ATLAS_NAME = {v: k for k, v in ALIAS.items()}
EXCLUDED = {"TimberIN": "founder instruction, 12 Nov 2026: excluded until Republic of Ireland delivery is verified"}
BESPOKE_ONLY = {"The Mobile Pods"}          # no products in the sauna explorer; public PlotNua showcase
EXCLUDED_TEXT = ["TimberIN", "woodenhottubsale", "PLOTNUA4"]
DISCLOSURE = "PlotNua has no commercial arrangement with any maker listed here"
NS = "Not stated by the maker"
ROUTE = {"kit": "Kit", "assembled": "Delivered assembled", "made-to-order": "Made to order", "installed": "Supplied and installed"}
LEVEL = {"supplier": "Maker-wide statement", "product": "Stated on the product page"}
WORDS = {6: "six", 7: "seven", 8: "eight", 9: "nine", 10: "ten"}
TRACKING = re.compile(r"[?&](utm_|fbclid|gclid)", re.I)


def E(s):
    return H.escape(s, quote=True)


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return f.read()


def host(u):
    return urlparse(u).netloc.lower().removeprefix("www.")


def cell(v, label):
    v = v if v else None
    inner = E(v) if v else '<span class="sx-ns">%s</span>' % NS
    return '<td data-label="%s">%s</td>' % (label, inner)


def render(ev):
    when = dt.date.fromisoformat(ev["captured"])
    day = "%d %s %d" % (when.day, when.strftime("%B"), when.year)
    out = ['<div class="sx">']
    for m in sorted(ev["makers"], key=lambda m: m["maker"].lower()):
        name = m["maker"]
        if m.get("profile"):
            name_html = '<a href="%s">%s</a>' % (E(m["profile"]), E(name))
        else:
            name_html = E(name)
        routes = "".join("<li>%s</li>" % ROUTE[r] for r in m["route"])
        d, i = m["delivery"], m["installation"]
        out.append('<article class="sx-maker" id="maker-%s">' % slug(name))
        out.append('<div class="sx-top"><h3>%s</h3><ul class="sx-routes" aria-label="How it is sold">%s</ul></div>'
                   % (name_html, routes))
        out.append('<dl class="sx-facts"><div><dt>Delivery</dt><dd>%s<span class="sx-lvl">%s</span></dd></div>'
                   '<div><dt>Installation</dt><dd>%s<span class="sx-lvl">%s</span></dd></div></dl>'
                   % (E(d["text"]), LEVEL[d["level"]], E(i["text"]), LEVEL[i["level"]]))
        if m["products"]:
            out.append('<table class="sx-t"><caption class="pn-sr">%s models checked</caption><thead><tr>'
                       '<th scope="col">Model</th><th scope="col">Size</th><th scope="col">Capacity</th>'
                       '<th scope="col">Heater</th><th scope="col">Published price</th></tr></thead><tbody>' % E(name))
            for p in m["products"]:
                pr = p["price"]
                basis = "%s; VAT %s" % (pr["basis"], pr["vat"]) if not pr["vat"].startswith("including") \
                    else "%s; %s" % (pr["basis"], pr["vat"])
                lead = ("; " + p["lead_time"]) if p.get("lead_time") else ""
                out.append('<tr><td><a href="%s" target="_blank" rel="noopener noreferrer">%s</a></td>%s%s%s'
                           '<td data-label="Published price" class="sx-price">%s<span class="sx-basis">%s%s</span></td></tr>'
                           % (E(p["url"]), E(p["name"]), cell(p.get("external"), "Size"),
                              cell(p.get("capacity"), "Capacity"), cell(p.get("heater"), "Heater"),
                              E(pr["text"]), E(basis), E(lead)))
            out.append('</tbody></table>')
        if m.get("bespoke"):
            out.append('<p class="sx-bespoke">%s</p>' % E(m["bespoke"]["text"]))
        srcs = sorted(set(d.get("sources", []) + [p["url"] for p in m["products"]]
                          + ([m["bespoke"]["url"]] if m.get("bespoke") else [])))
        links = " &middot; ".join('<a href="%s" target="_blank" rel="noopener noreferrer">%s</a>'
                                  % (E(u), E(host(u) + urlparse(u).path.rstrip("/"))) for u in srcs)
        out.append('<p class="sx-src">Checked on the maker&rsquo;s own pages, %s: %s</p>' % (day, links))
        acts = []
        if m.get("profile"):
            acts.append('<a href="%s">PlotNua&rsquo;s %s profile &rarr;</a>' % (E(m["profile"]), E(name)))
        acts.append('<a href="%s" target="_blank" rel="noopener noreferrer">%s website &rarr;</a>'
                    % (E(m["site"]), E(name)))
        out.append('<p class="sx-links">%s</p>' % "".join(acts))
        out.append('</article>')
    out.append('</div>')
    out.append('<p class="sx-excl">Not compared here: one maker listed in Garden Retreat that publishes its prices in sterling '
               'and whose delivery to the Republic of Ireland PlotNua has not yet confirmed. Garden Retreat lists every '
               'sauna maker PlotNua has published.</p>')
    return "\n".join(out)


def splice(page, region):
    a, b = page.index(BEGIN) + len(BEGIN), page.index(END)
    return page[:a] + "\n" + region + "\n" + page[b:]


def explorer_sauna_makers(retreat_html):
    m = re.search(r'<script type="application/json" class="pn-mx-config" id="mx-data">(.*?)</script>', retreat_html, re.S)
    data = json.loads(m.group(1))
    tab = next(t for t in data["tabs"] if t["key"] == "saunas")
    return {mk["m"] for mk in tab["makers"]}


def guards(ev, page, files):
    bad = []
    names = [m["maker"] for m in ev["makers"]]
    # S1
    listed = explorer_sauna_makers(files[RETREAT])
    for n in names:
        atlas = ATLAS_NAME.get(n, n)
        if atlas not in listed and n not in BESPOKE_ONLY:
            bad.append("S1 %s is not a publicly listed sauna maker in Garden Retreat" % n)
        if n in BESPOKE_ONLY and not next(m for m in ev["makers"] if m["maker"] == n).get("profile"):
            bad.append("S1 bespoke-only maker %s has no public PlotNua profile" % n)
    covered = {ATLAS_NAME.get(n, n) for n in names}
    for n in sorted(listed - covered - set(EXCLUDED)):
        bad.append("S1 publicly listed sauna maker %s is neither compared nor declared excluded" % n)
    # S2
    main = page[page.index('<main id="pn-main">'):page.index("</main>")]
    for t in EXCLUDED_TEXT + files["_held"]:
        if t and t.lower() in page.lower():
            bad.append("S2 excluded or held organisation reaches the page: %s" % t)
    for h in re.findall(r'href="([^"]+)"', page):
        if h.endswith("-preview.html") or "-preview.html#" in h:
            bad.append("S2 private preview linked: %s" % h)
    # S3
    sitemap = files["sitemap.xml"]
    for m in ev["makers"]:
        if m.get("profile"):
            p = m["profile"]
            if p not in files["_profiles"]:
                bad.append("S3 profile does not exist: %s" % p)
            else:
                ph = files["_profiles"][p]
                if 'name="robots" content="index' not in ph:
                    bad.append("S3 profile is not indexable: %s" % p)
                if "https://plotnua.ie/%s</loc>" % p not in sitemap:
                    bad.append("S3 profile is not in the sitemap: %s" % p)
        site = host(m["site"])
        for p in m["products"]:
            if host(p["url"]) != site:
                bad.append("S3 %s source is not on the maker's host: %s" % (m["maker"], p["url"]))
    for h in re.findall(r'href="(https?://[^"]+)"', main):
        if TRACKING.search(H.unescape(h)):
            bad.append("S3 outbound link carries tracking parameters: %s" % h)
    # S4
    for m in ev["makers"]:
        for p in m["products"]:
            pr = p.get("price") or {}
            for k in ("text", "basis", "vat"):
                if not pr.get(k):
                    bad.append("S4 %s / %s has no price %s" % (m["maker"], p.get("name"), k))
            if not p.get("url"):
                bad.append("S4 %s / %s has no source URL" % (m["maker"], p.get("name")))
        if not m["products"] and not m.get("bespoke"):
            bad.append("S4 %s has neither products nor a bespoke statement" % m["maker"])
    if re.search(r'<td data-label="[^"]+">\s*</td>', main):
        bad.append("S4 an empty cell is published")
    # S5
    known = set(re.findall(r"€[\d,]+(?:\.\d+)?", json.dumps(ev, ensure_ascii=False)))
    shown = set(re.findall(r"€[\d,]+(?:\.\d+)?", H.unescape(re.sub(r"<[^>]+>", " ", main))))
    for x in sorted(shown - known):
        bad.append("S5 a price figure is not in the evidence: %s" % x)
    # S6
    for src in re.findall(r'<(?:img|source)[^>]+(?:src|srcset)="([^"\s]+)', page):
        if not re.match(r"/?assets/brand/", src):
            bad.append("S6 an image other than PlotNua's brand assets: %s" % src)
    # S7
    cap = dt.date.fromisoformat(ev["captured"])
    today = dt.date.fromisoformat(os.environ.get("PN_TODAY") or dt.date.today().isoformat())
    if (today - cap).days > 30:
        bad.append("S7 evidence captured %s is more than 30 days old" % cap)
    for m in ev["makers"]:
        for p in m["products"]:
            hit = re.search(r"until (\d{1,2}) (\w+) (\d{4})", p["price"]["basis"])
            if hit and "introductory" in p["price"]["basis"]:
                end = dt.datetime.strptime(" ".join(hit.groups()), "%d %b %Y").date()
                if today > end:
                    bad.append("S7 %s / %s: introductory price ended %s" % (m["maker"], p["name"], end))
    # S8
    if DISCLOSURE not in re.sub(r"\s+", " ", page):
        bad.append("S8 the no-commercial-arrangement disclosure is missing")
    active = {a["key"] for a in json.loads(files["_register"])["active"]}
    for n in names:
        if hashlib.sha256(ATLAS_NAME.get(n, n).encode()).hexdigest()[:12] in active:
            bad.append("S8 %s has an ACTIVE commercial arrangement: the disclosure would be false" % n)
    # S9
    first = re.search(r'<a [^>]*href="([^"]+)"', main)
    if not first or first.group(1) != RETREAT:
        bad.append("S9 the first link in <main> is not the parent Discovery")
    hero = main[:main.index("</section>")]
    if WORDS.get(len(names), str(len(names))) + " makers" not in hero:
        bad.append("S9 the hero does not state the number of makers compared (%d)" % len(names))
    return bad


def load_files():
    files = {RETREAT: read(RETREAT), "sitemap.xml": read("sitemap.xml"),
             "_register": read(os.path.join("atlas-tools", "commercial-arrangements-register.json"))}
    pre = json.loads(read(os.path.join("atlas-tools", "preview-only-suppliers.json")))
    wel = json.loads(read("wellness-universe-v1.json"))
    held = [s["name"] for s in pre.get("suppliers", []) if s.get("name") and not s.get("removed")]
    held += wel["publicationGate"]["heldOrganisations"]
    files["_held"] = sorted(set(held))
    files["_profiles"] = {}
    for f in os.listdir(os.path.join(ROOT, "suppliers")):
        files["_profiles"]["suppliers/" + f] = read(os.path.join("suppliers", f))
    return files


def run(ev, page, files):
    region = render(ev)
    new = splice(page, region)
    return new, guards(ev, new, files)


def prove(ev, page, files):
    import copy
    cases = []

    def mut(label, f_ev=None, f_page=None, f_files=None):
        e, p, fs = copy.deepcopy(ev), page, dict(files)
        if f_ev: f_ev(e)
        if f_files: f_files(fs)
        new = splice(p, render(e))
        if f_page: new = f_page(new)
        cases.append((label, guards(e, new, fs)))

    mut("CONTROL")
    mut("S1 a maker not in the explorer is added", f_ev=lambda e: e["makers"].append(dict(e["makers"][0], maker="Sauna Experts")))
    mut("S1 a listed maker is silently dropped", f_ev=lambda e: e["makers"].pop(4))
    mut("S2 TimberIN is put back", f_page=lambda p: p.replace("</main>", "<p>TimberIN</p></main>"))
    mut("S2 a private preview is linked", f_page=lambda p: p.replace("</main>", '<a href="ognyx-preview.html">x</a></main>'))
    mut("S3 a profile path is wrong", f_ev=lambda e: e["makers"][0].update(profile="suppliers/arctic.html"))
    mut("S3 a product source is off-host", f_ev=lambda e: e["makers"][0]["products"][0].update(url="https://example.com/x"))
    mut("S3 a tracked outbound link", f_page=lambda p: p.replace("</main>", '<a href="https://pineca.ie/?utm_source=x">x</a></main>'))
    mut("S4 a price without VAT statement", f_ev=lambda e: e["makers"][0]["products"][0]["price"].update(vat=""))
    mut("S5 an invented price", f_page=lambda p: p.replace("</main>", "<p>from €999</p></main>"))
    mut("S6 a supplier image", f_page=lambda p: p.replace("</main>", '<img src="https://x.ie/a.jpg" alt=""></main>'))
    mut("S7 stale evidence", f_ev=lambda e: e.update(captured="2026-09-01"))
    mut("S8 disclosure removed", f_page=lambda p: p.replace(DISCLOSURE, "PlotNua is independent"))
    mut("S8 an active arrangement", f_files=lambda fs: fs.update(_register=json.dumps({"active": [{"key": hashlib.sha256(b"OGNYX").hexdigest()[:12]}]})))
    mut("S9 parent link removed", f_page=lambda p: p.replace('<p class="parent"><a href="discovery-garden-retreat.html">', '<p class="parent"><a href="discoveries.html">', 1))
    ok = True
    for label, bad in cases:
        expect = not bad if label == "CONTROL" else bool(bad) and bad[0].split()[0] == label.split()[0]
        if label != "CONTROL" and bad and not any(b.split()[0] == label.split()[0] for b in bad):
            expect = False
        ok &= expect
        print("  %s  %s%s" % ("CAUGHT" if expect else "MISSED", label, ("\n           -> " + bad[0]) if bad else ""))
    print("%d of %d correct" % (sum(1 for l, b in cases if (not b if l == "CONTROL" else any(x.split()[0] == l.split()[0] for x in b))), len(cases)))
    return ok


def main():
    ev = json.loads(read(EVIDENCE))
    page = read(PAGE)
    files = load_files()
    if "--prove" in sys.argv:
        sys.exit(0 if prove(ev, page, files) else 1)
    new, bad = run(ev, page, files)
    if "--check" in sys.argv:
        if new != page:
            bad.insert(0, "the generated comparison is out of date: run the builder")
    elif not bad:
        with open(os.path.join(ROOT, PAGE), "w", encoding="utf-8") as f:
            f.write(new)
    if bad:
        print("GARDEN SAUNAS GUIDE · REFUSED")
        for b in bad:
            print("  - " + b)
        sys.exit(1)
    print("GARDEN SAUNAS GUIDE · %s — S1-S9 pass · %d makers, %d models, evidence %s"
          % ("CHECK OK" if "--check" in sys.argv else "BUILT", len(ev["makers"]),
             sum(len(m["products"]) for m in ev["makers"]), ev["captured"]))


if __name__ == "__main__":
    main()
