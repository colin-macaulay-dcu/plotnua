def page(lib, ideas):
    t = library_without_board(lib)
    reps = [(r"<title>[^<]*</title>", "<title>Idea Board | PlotNua</title>"),
            (r'<meta name="description" content="[^"]*">', '<meta name="description" content="Have an idea for what an Irish home, garden or street could do? Add it to the PlotNua Idea Board.">'),
            (r'<meta name="robots" content="[^"]*">', '<meta name="robots" content="noindex, follow">'),
            (r'<link rel="canonical" href="[^"]*">', '<link rel="canonical" href="https://plotnua.ie/ideas.html">'),
            (r'<meta property="og:title" content="[^"]*">', '<meta property="og:title" content="Idea Board | PlotNua">'),
            (r'<meta property="og:description" content="[^"]*">', '<meta property="og:description" content="What could your property do? Add an idea to the board.">'),
            (r'<meta property="og:url" content="[^"]*">', '<meta property="og:url" content="https://plotnua.ie/ideas.html">'),
            (r'<meta name="twitter:title" content="[^"]*">', '<meta name="twitter:title" content="Idea Board | PlotNua">'),
            (r'<meta name="twitter:description" content="[^"]*">', '<meta name="twitter:description" content="What could your property do? Add an idea to the board.">')]
    for rx, new in reps:
        if len(re.findall(rx, t)) != 1: die("Library shell: %s not found exactly once" % rx)
        t = re.sub(rx, lambda m: new, t, count=1)
    t = re.sub(r'<script type="application/ld\+json">.*?</script>\n?', "", t, flags=re.S)
    i, j = t.index('<div class="wrap">'), t.rindex("</div>\n\n<script>")
    t = t[:i] + body(ideas) + t[j + len("</div>\n\n"):]
    k = t.rindex("<script>"); t = t[:k] + PAGE_JS + "</body>\n</html>\n"
    t = t.replace("</head>", PAGE_CSS + "</head>", 1)
    banner = not H.has_own_banner(t[t.index("<body"):])
    for k, new in (("BAR", H.bar("ideas.html", H.RAIL_BEGIN in t, banner)), ("ROW", H.row("ideas.html"))):
        rx = re.compile(re.escape("<!-- PLOTNUA HEADER v2 · %s · BEGIN" % k) + r".*?" + re.escape("<!-- PLOTNUA HEADER v2 · %s · END -->" % k) + r"\n", re.S)
        if len(rx.findall(t)) != 1: die("Library shell: header %s block not found exactly once" % k)
        t = rx.sub(lambda m: new, t, count=1)
    t = t.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n<!-- PLOTNUA IDEA BOARD PAGE · generated by atlas-tools/build-idea-board.py from the approved ideas — do not hand-edit -->\n", 1)
    return t


