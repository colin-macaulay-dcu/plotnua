def library(cur, ideas):
    block = re.compile(r"[ \t]*" + re.escape(CARD_B) + r".*?" + re.escape(CARD_E) + r"\n", re.S)
    if block.search(cur): t = block.sub(lambda m: card(ideas), cur, count=1)
    elif TEASER.search(cur): t = TEASER.sub(lambda m: card(ideas), cur, count=1)
    else: die("discoveries.html has neither the teaser card nor the Idea Board card")
    t = re.sub(re.escape(CSS_B) + r".*?" + re.escape(CSS_E) + r"\n\n", "", t, flags=re.S)
    # placed before the Library labels' styles (which sit directly above the a11y block), so either builder can run
    anchor = LABELS_CSS if LABELS_CSS in t else CSS_ANCHOR
    if t.count(anchor) != 1: die("the Library stylesheet anchor is not present exactly once")
    t = t.replace(anchor, CARD_CSS + anchor, 1)
    return t


def library_without_board(t):
    """The Library with the Idea Board layer taken out (for the 'nothing else changed' comparison)."""
    t = re.sub(r"[ \t]*" + re.escape(CARD_B) + r".*?" + re.escape(CARD_E) + r"\n", "", t, flags=re.S)
    t = TEASER.sub("", t)
    return re.sub(re.escape(CSS_B) + r".*?" + re.escape(CSS_E) + r"\n\n", "", t, flags=re.S)


