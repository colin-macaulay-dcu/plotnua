FORBIDDEN_JS = ("fetch(", "XMLHttpRequest", "localStorage", "sessionStorage", "document.cookie",
                "location", "history.", "sendBeacon", "dataLayer", "gtag", "Math.random", ".sort(",
                "href", "http", "window.open", "<a ")


def die(msg):
    print("REFUSED: " + msg + " -- nothing written")
    sys.exit(2)

# THE ONE PERMITTED LINK (14 Oct 2026, founder decision "House as Power Station
# Provider Explorer · final refinement"). provider-explorer.js may contain
# exactly one link construct: the offLink() function, pinned here by sha256 and
# called once. It is removed before the forbidden-content scan, so every other
# link, fetch or storage use still refuses.
OFFLINK_SHA = "caf2a7f7229b2e5aaf003d74665cd96f8256ddd2bb766338239779c4a9b7f255"


def strip_offlink(code):
    i = code.find("  function offLink(o) {")
    if i < 0 or code.count("function offLink(") != 1 or code.count("offLink(o)") != 2:
        die("P3 provider-explorer.js must define offLink() once and call it once")
    j = code.index("\n  }\n", i) + len("\n  }\n")
    if hashlib.sha256(code[i:j].encode()).hexdigest() != OFFLINK_SHA:
        die("P3 offLink() in provider-explorer.js differs from its pinned form")
    return code[:i] + code[j:]


def sha(path):
    return hashlib.sha256((ROOT / path).read_bytes()).hexdigest()


def esc(s):
    return (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;"))


def section(u):
    tabs = u["tabs"]
    btns = []
    for i, t in enumerate(tabs):
        btns.append(
            '        <button type="button" class="mx-tab" role="tab" id="px-t-%s" aria-selected="%s" aria-controls="px-pane" data-k="%s"%s>%s <span class="mx-n">%d</span></button>'
            % (t["key"], "true" if i == 0 else "false", t["key"], "" if i == 0 else ' tabindex="-1"', esc(t["label"]), len(t["orgs"])))
    names = "; ".join("%s: %s" % (t["label"], ", ".join(o["name"] for o in t["orgs"])) for t in tabs)
    cfg = json.dumps({"tabs": tabs}, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    return (
        BEGIN +
        '  <section class="article-section reveal" id="explore-providers" data-pn-provider-explorer aria-labelledby="px-title">\n'
        '    <div class="kicker">Organisations and Services</div>\n'
        '    <h2 id="px-title">Explore garden-sharing organisations</h2>\n'
        '    <p>Discover services and organisations already helping people access growing space in Ireland.</p>\n'
        '    <div class="mx" id="px">\n'
        '      <div class="mx-tabs" role="tablist" aria-label="Kind of organisation">\n' + "\n".join(btns) + "\n"
        '      </div>\n'
        '      <div class="mx-pane" id="px-pane" role="tabpanel" aria-labelledby="px-t-%s">\n' % tabs[0]["key"] +
        '        <p class="mx-line" id="px-line">%s</p>\n' % esc(tabs[0]["note"]) +
        '        <ul class="mx-legend"><li><span class="px-ring" aria-hidden="true"></span>%s</li></ul>\n' % esc(STATEMENT) +
        '        <ul class="mx-grid" id="px-grid"></ul>\n'
        '        <noscript><p class="mx-line">%s.</p></noscript>\n' % esc(names) +
        '      </div>\n'
        '    </div>\n'
        '    <p class="mx-foot">Listed A to Z and never ranked. Nothing here is an introduction.</p>\n'
        '    <script type="application/json" class="pn-px-config" id="px-data">' + cfg + '</script>\n'
        '    <script src="provider-explorer.js"></script>\n'
        '  </section>\n' + END)


def strip(html):
    """Remove everything this builder adds and revert the corrections."""
    html = re.sub(r"\n?" + re.escape(BEGIN) + r"[\s\S]*?" + re.escape(END), "", html)
    html = html.replace(STYLE_END + "\n" + CSS_LINK, STYLE_END)
    for _, old, new in CORRECTIONS:
        html = html.replace(new, old)
    return html


def build(current):
    u = json.loads(UNIVERSE.read_text(encoding="utf-8"))
    html = strip(current)
    for label, old, new in CORRECTIONS:
        if html.count(old) != 1:
            die("P10 correction anchor not found exactly once: " + label)
        html = html.replace(old, new)
    if html.count(STYLE_END) != 1:
        die("P12 head style end marker not found exactly once")
    html = html.replace(STYLE_END, STYLE_END + "\n" + CSS_LINK)
    if html.count(ANCHOR) != 1:
        die("P8 placement anchor (end of 'Three things worth settling first') not found exactly once")
    html = html.replace(ANCHOR, ANCHOR + "\n" + section(u))
    return html, u


def guards(html, u):
    # P3b · the Borrowed Garden carries no official link, so offLink() renders
    # nothing here and the page is unchanged (14 Oct 2026)
    if any("link" in o for t in u["tabs"] for o in t["orgs"]):
        die("P3 a Borrowed Garden organisation carries a link; offLink() is for the House as Power Station only")
    # P1
    r = subprocess.run([sys.executable, str(UBUILD), "--check"], capture_output=True, text=True)
    if r.returncode != 0:
        die("P1 the provider universe is not up to date or fails its own guards:\n" + r.stdout + r.stderr)
    # P2
    for f, pin in PINS.items():
        if sha(f) != pin:
            die("P2 %s does not match its pin (%s)" % (f, sha(f)))
    # P3
    js = (ROOT / "provider-explorer.js").read_text(encoding="utf-8")
    code = strip_offlink(re.sub(r"/\*[\s\S]*?\*/", "", js))
    for bad in FORBIDDEN_JS:
        if bad in code:
            die("P3 provider-explorer.js contains %r" % bad)
    # P4
    a = html.index(BEGIN); b = html.index(END)
    sec = html[a:b]
    for bad in ("<a ", "href=", "<form", "<input", "<iframe", "http"):
        if bad in sec.replace('src="provider-explorer.js"', ""):
            die("P4 the explorer section contains %r" % bad)
    base = strip(html)
    if len(re.findall(r'href="https?://', html)) != len(re.findall(r'href="https?://', base)):
        die("P4 the page gained an external link")
    # P5
    if u["partnersCount"] != 0:
        die("P5 partnersCount is not 0")
    for t in u["tabs"]:
        for o in t["orgs"]:
            if o.get("partner") is not False:
                die("P5 %s is not partner:false" % o["code"])
    if sec.count(STATEMENT) != 1:
        die("P5 the single statement that these organisations are researched, not partners, is missing or repeated")
    if re.search(r"no relationship with|PlotNua partners: none|None of them is a PlotNua partner", sec):
        die("P5 a repeated partnership disclaimer has come back")
    # P6
    labels = [t["label"] for t in u["tabs"]]
    if labels != ["Garden-sharing services", "Other growing opportunities"]:
        die("P6 tabs are %r" % labels)
    for o in u["tabs"][0]["orgs"]:
        if "Council" in o["name"]:
            die("P6 a council is in the garden-sharing tab")
    for o in u["tabs"][1]["orgs"]:
        if "This is not garden-sharing." not in o["offers"]:
            die("P6 council %s is not labelled as not garden-sharing" % o["code"])
    # P7
    m = re.search(r'<script type="application/json" class="pn-px-config" id="px-data">([\s\S]*?)</script>', sec)
    if not m or json.loads(m.group(1).replace("<\\/", "</")) != {"tabs": u["tabs"]}:
        die("P7 the embedded configuration does not equal the universe")
    # P8
    i_faq = html.index("<h2>Three things worth settling first.</h2>")
    i_px = html.index('id="explore-providers"')
    i_pc = html.index('id="discover-your-property"')
    if not (i_faq < i_px < i_pc):
        die("P8 explorer is not between 'Three things worth settling first' and the Property Check panel")
    if html.count(PC_LINK) != base.count(PC_LINK) or html.count(PC_LINK) < 1:
        die("P8 the Property Check link changed")
    nxt = html[b + len(END):].lstrip()
    if not nxt.startswith("</div>"):
        die("P8 explorer is not inside the article wrapper")
    # P9
    try:
        head = subprocess.run(["git", "-C", str(ROOT), "show", "HEAD:" + PAGE_NAME],
                              capture_output=True, text=True, check=True).stdout
        if strip(head) != base:
            die("P9 the rest of the page differs from git HEAD beyond the explorer, its link and the corrections")
    except (subprocess.CalledProcessError, FileNotFoundError):
        print("  P9 skipped: git HEAD not available")
    # P10
    for label, old, new in CORRECTIONS:
        if html.count(new) != 1 or old in html:
            die("P10 correction not applied cleanly: " + label)
    if "last reviewed in August 2026" in html:
        die("P10 superseded Homegrown.ie review date still present")
    # P11
    for t in TOKENS:
        if t + ":" not in html:
            die("P11 host page does not define " + t)
    # P12
    if html.count(CSS_LINK) != 1 or html.index(CSS_LINK) > html.index("</head>"):
        die("P12 stylesheet link missing, duplicated or outside <head>")
    if html.count('class="pn-px-config"') != 1 or html.count('<script src="provider-explorer.js"></script>') != 1:
        die("P12 config or script missing or duplicated")
    if "data-pn-maker-explorer" in html:
        die("P12 the Maker Explorer must not be on this page")


def main(argv):
    if "--apply" not in argv and "--check" not in argv:
        print(__doc__); sys.exit(1)
    current = PAGE.read_text(encoding="utf-8")
    html, u = build(current)
    guards(html, u)
    n = sum(len(t["orgs"]) for t in u["tabs"])
    summary = "%d organisations in %d tabs (%s)" % (n, len(u["tabs"]), ", ".join("%s %d" % (t["key"], len(t["orgs"])) for t in u["tabs"]))
    if "--check" in argv:
        if html != current:
            print("CHECK FAILED: %s is out of date; run --apply" % PAGE_NAME); sys.exit(1)
        print("%s: %s · CHECK OK — P1-P12 pass" % (PAGE_NAME, summary)); return
    PAGE.write_text(html, encoding="utf-8")
    print("%s: %s · APPLIED — P1-P12 pass" % (PAGE_NAME, summary))


if __name__ == "__main__":
    main(sys.argv[1:])
