#!/usr/bin/env python3
"""SEO-GR2 (founder approval 8 Nov 2026): internal links to the homepage point at its canonical URL "/".

The homepage's canonical is https://plotnua.ie/ but most internal links named /index.html, a
second URL GitHub Pages serves with the same content (SEO-GR1 finding T3). This rewrites ONLY
href attribute values that resolve to the site-root /index.html, to "/", keeping any query string
and #fragment ("index.html#discover" -> "/#discover"). Nothing else on the page changes: classes,
ids, aria labels, text, tracking and scripts are untouched.

Never touched (by rule):
  plotart/**            PlotArt is protected (its own index.html is a different page anyway)
  *-preview.html        private supplier previews (noindex; not part of the public site)
  atlas-tools/, governance/, supplier-preview-system/, worker/, node_modules/
  privacy.html          its text is pinned by the Privacy V3-V6 builders, and artist-register.html is
  artist-register.html  built from privacy.html's page shell: in both, only the header bar's brand link
                        (generated by pn_header.py, which now emits "/") changes; the legacy brand mark and
                        the footer's "Discoveries" link stay "index.html" for a dedicated privacy release
A link whose target is NOT the root homepage (for example plotart/index.html) is never changed.

  python3 atlas-tools/seo-gr2-home-links.py            # report what would change (exit 1 if any)
  python3 atlas-tools/seo-gr2-home-links.py --apply    # rewrite
  python3 atlas-tools/seo-gr2-home-links.py --check    # exit 0 only when no public page links to /index.html
"""
import posixpath, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKIP_DIRS = ("plotart/", "atlas-tools/", "governance/", "supplier-preview-system/", "worker/", "node_modules/", ".git/",
             "atlas-visual-references/", "commercial/")
SKIP_PAGES = {"privacy.html", "artist-register.html"}   # pinned legal shell (Privacy V3-V6); see the docstring
HREF = re.compile(r'href="([^"]*)"')


def public_pages():
    for p in sorted(ROOT.rglob("*.html")):
        rel = p.relative_to(ROOT).as_posix()
        if rel.startswith(SKIP_DIRS) or rel.endswith("-preview.html") or rel in SKIP_PAGES:
            continue
        yield rel, p


def to_root_home(page, href):
    """Return the replacement for href if it resolves to the root /index.html, else None."""
    base, sep, tail = re.match(r"([^?#]*)([?#]?)(.*)", href).groups()
    if base.startswith("https://plotnua.ie"):
        path = base[len("https://plotnua.ie"):]
    elif base.startswith("/"):
        path = base
    elif re.match(r"^[a-z][a-z0-9+.-]*:", base) or base == "":
        return None
    else:
        path = "/" + posixpath.normpath(posixpath.join(posixpath.dirname(page), base))
    if path != "/index.html":
        return None
    return "/" + (sep + tail if sep else "")


def run(apply):
    total, files = 0, {}
    for rel, p in public_pages():
        txt = p.read_text(encoding="utf-8")
        n = 0

        def sub(m):
            nonlocal n
            new = to_root_home(rel, m.group(1))
            if new is None:
                return m.group(0)
            n += 1
            return f'href="{new}"'
        out = HREF.sub(sub, txt)
        if n:
            files[rel] = n
            total += n
            if apply:
                p.write_text(out, encoding="utf-8")
    return total, files


if __name__ == "__main__":
    apply = "--apply" in sys.argv
    total, files = run(apply)
    for f, n in files.items():
        print(f"{n:3d}  {f}")
    print(("REWROTE" if apply else "FOUND") + f" {total} homepage link(s) to /index.html in {len(files)} public page(s)")
    if "--check" in sys.argv:
        sys.exit(0 if total == 0 else 1)
    sys.exit(0 if (apply or total == 0) else 1)
