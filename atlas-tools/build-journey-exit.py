# E4 — editorial prose outside the region byte-identical, against disk. Runs
#      before the raw byte guard so a reworded sentence is reported as a copy
#      change rather than as an anonymous byte difference.
def prose(t):
    t = strip_region(t)
    t = re.sub(r"<script.*?</script>", " ", t, flags=re.S | re.I)
    t = re.sub(r"<style.*?</style>", " ", t, flags=re.S | re.I)
    t = re.sub(r"<!--.*?-->", " ", t, flags=re.S)
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", t)).strip()


for r in results:
    if prose(disk(r["file"])) != prose(r["text"]):
        die("E4 %s: editorial prose changed" % r["file"])
print("  E4  all journey editorial prose outside the region byte-identical  OK")

# E6 — THE FROZEN DECISION EXPERIENCE. <main> … </main> byte-identical,
#      compared against the page on disk. For DISC-025 this element IS the
#      frozen V2 check / result / interest experience, so this is the proof the
#      founder ruling requires.
MAIN_RE = re.compile(r"<main\b.*?</main>", re.S)
for r in results:
    a = MAIN_RE.search(disk(r["file"])).group(0)
    b = MAIN_RE.search(r["text"]).group(0)
    if a != b:
        die("E6 %s: the <main> decision experience changed" % r["file"])
print("  E6  <main> … </main> byte-identical on all ten, against the page on\n"
      "      disk — questions, options, engine, result, evidence, interest\n"
      "      and copy all untouched  OK")

# E3 — every pre-existing inline <style> and <script> body byte-identical
#      against disk. The region adds exactly one <style> body and no <script>.
def bodies(t, tag):
    return [x for x in re.findall(r"<%s(?:\s[^>]*)?>(.*?)</%s>" % (tag, tag),
                                  t, re.S) if x.strip()]


for r in results:
    d = disk(r["file"])
    for tag in ("style", "script"):
        if bodies(d, tag) != bodies(strip_region(r["text"]), tag):
            die("E3 %s: a pre-existing inline <%s> body changed" % (r["file"], tag))
    if len(bodies(r["text"], "style")) != len(bodies(d, "style")) + 1:
        die("E3 %s: the region should add exactly one <style> body" % r["file"])
    if len(bodies(r["text"], "script")) != len(bodies(d, "script")):
        die("E3 %s: the region must add no <script> body" % r["file"])
print("  E3  every pre-existing inline <style>/<script> body byte-identical;\n"
      "      region adds one <style> and zero <script>  OK")

# E2 — the catch-all. EVERY byte outside the injection point unchanged, against
#      the page on disk. Deliberately LAST of the comparison guards: it would
#      otherwise claim every failure the specific guards above describe better.
for r in results:
    if strip_region(r["text"]) != disk(r["file"]):
        die("E2 %s changed outside the injection point" % r["file"])
print("  E2  every byte outside the injection point unchanged (round-trip\n"
      "      against the page on disk)  OK")

# E7 — the region carries no storage, no analytics, no network, no script
