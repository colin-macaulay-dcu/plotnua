# ======================================================================= BUILD
results = []
for f in CHECKS:
    p = ROOT / f
    original = p.read_text(encoding="utf-8")
    base = strip_region(original)          # idempotent: re-running replaces
    i = base.index("</main>") + len("</main>")
    out = base[:i] + "\n\n" + REGION + "\n" + base[i:]
    results.append({"file": f, "base": base, "text": out, "after": sha(out)})


# THE GUARDS COMPARE AGAINST THE FILE ON DISK, NOT AGAINST THE BUILDER'S OWN
# INTERMEDIATE. The mutation proof showed why: a builder that corrupts `base`
# before deriving `out` makes a base-versus-out comparison trivially pass, and
# three guards went BLIND against exactly that. Re-reading the page is the only
# comparison a defective builder cannot launder.
def disk(f):
    return strip_region((ROOT / f).read_text(encoding="utf-8"))


for r in results:
    r["before"] = sha(disk(r["file"]))

# ====================================================================== GUARDS
print()

# E1 — one canonical region, byte-identical on all ten
regions = set()
for r in results:
    a = r["text"].index(BEGIN)
    b = r["text"].index(END) + len(END)
    regions.add(sha(r["text"][a:b]))
if len(regions) != 1:
    die("E1 the injected region differs between pages: %r" % regions)
print("  E1  injected region sha256 identical on all ten checks\n"
      "      %s  OK" % list(regions)[0])

# E6b — the region really is OUTSIDE <main>
for r in results:
    if r["text"].index(BEGIN) < r["text"].index("</main>"):
        die("E6b %s: the region landed inside <main>" % r["file"])
print("  E6b the region sits after </main> on every check, never inside  OK")

# E5 — idempotence. Runs before the structural guards so that a double
#      injection is reported as a double injection, not as a style-count
#      anomaly downstream.
for r in results:
    if r["text"].count(BEGIN) != 1 or r["text"].count(END) != 1:
        die("E5 %s does not carry exactly one region" % r["file"])
    again = strip_region(r["text"])
    i = again.index("</main>") + len("</main>")
    if again[:i] + "\n\n" + REGION + "\n" + again[i:] != r["text"]:
        die("E5 %s is not idempotent under re-injection" % r["file"])
print("  E5  exactly one region per page, and re-injection is idempotent  OK")

# E9 — NO EXISTING CALL TO ACTION WEAKENED. Every outbound anchor that existed
#      on disk still exists, with its text unchanged.
HREF_RE = re.compile(r'<a\b[^>]*href="([^"]+)"[^>]*>(.*?)</a>', re.S)
for r in results:
    before = HREF_RE.findall(disk(r["file"]))
    after = HREF_RE.findall(r["text"])
    missing = [x for x in before if x not in after]
    if missing:
        die("E9 %s: a pre-existing anchor was lost or reworded: %r"
            % (r["file"], missing[:3]))
print("  E9  every pre-existing anchor (href AND its text) still present on\n"
      "      all ten — no CTA removed, reworded, demoted or restyled  OK")

# E14 — the before/after journey-exit census, computed not asserted. Runs
#       before E12 so that a destination quietly swapped out is reported as a
#       census failure rather than as a missing literal.
print("\n  E14 JOURNEY-EXIT CENSUS")
print("      %-42s %-10s %s" % ("check", "before", "after"))
WANT = ["discoveries.html", "search.html", "your-plot.html", "index.html"]


def have(t):
    hs = [h for h, _ in HREF_RE.findall(t)]
    return "".join("D" if any(w in h for h in hs) else "." for w in WANT)


for r in results:
    b, a = have(disk(r["file"])), have(r["text"])
    print("      %-42s %-10s %s" % (r["file"], b, a))
