# E8 — the region introduces no external asset, and specifically does not
#      bring the Search pill or its shared assets onto a journey page
for bad in ("search.css", "search.js", "pns-", "<link", "<img", "src=",
            "https://", "http://"):
    if bad in REGION:
        die("E8 the region references the external asset or prefix %r" % bad)
