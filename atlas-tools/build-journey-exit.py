def strip_region(text):
    # The leading \n* matters. The splice is "\n\n" + REGION + "\n", and this
    # pattern removes exactly that, so stripping is newline-symmetric wherever
    # the region sits. Without it, a region spliced at the WRONG offset would
    # leave a stray newline and be reported by the byte guard (E2) instead of
    # the boundary guard (E6b) — the mutation proof caught precisely that
    # misattribution, and this is the fix.
    return re.sub(r"\n*" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?",
                  "", text, flags=re.S)


