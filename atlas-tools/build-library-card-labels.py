#!/usr/bin/env python3
"""
DISCOVERY LIBRARY · card labels (founder approval of the card-label proposal, 1 Nov 2026; prepared on a branch,
NOT deployed).

Three layers, each with one place and one voice:

  * CATEGORY        the existing uppercase kicker, now alone in its row (no status boxes beside it);
  * VISITOR ACTION  one quiet line beneath the description, after a fine rule, from a closed vocabulary in
                    atlas-tools/discovery-library-labels.json, and ONLY when this builder can prove from the
                    Discovery page itself that the tool is there (a label can never claim a missing feature);
  * AI DISCLOSURE   a small chip on the image, the register's exact approved label, shown if and only if the
                    card image is a declared AI_ILLUSTRATION record in image-provenance-records.json (or a
                    derivative of one). Never typed by hand; legacy images are left exactly as they are.

Nothing else changes: card order, images, titles, descriptions, categories, alt text, links and navigation are
checked byte for byte against the page without this layer. No Discovery page is written.

  python3 atlas-tools/build-library-card-labels.py          build
  python3 atlas-tools/build-library-card-labels.py --check  verify, write nothing
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PAGE = ROOT / "discoveries.html"
MAP = ROOT / "atlas-tools/discovery-library-labels.json"
REG = ROOT / "image-provenance-records.json"
CHECK = "--check" in sys.argv
OLD_SPANS = re.compile(r'\n[ \t]*<span class="lib-(?:live|soon|atlas|ai)"[^>]*>[^<]*</span>')
CARD = re.compile(r'<a class="lib-card" href="([^"]+)"[^>]*>.*?</a>', re.S)
CSS_BEGIN, CSS_END = "/* PLOTNUA LIBRARY LABELS v1 · BEGIN · generated by atlas-tools/build-library-card-labels.py */", "/* PLOTNUA LIBRARY LABELS v1 · END */"
CSS = CSS_BEGIN + """
/* Visitor action: an editorial footnote beneath the description, led by a fine rule in the category colour. */
.lib-act{ display:flex; align-items:center; gap:10px; margin-top:16px;
  font-size:13px; font-weight:500; line-height:1.3; letter-spacing:.02em; color:var(--ink); opacity:.88; }
.lib-act::before{ content:""; flex:0 0 16px; height:1px; background:var(--accent); }
/* AI disclosure: on the image it describes, bottom-left, legible over bright skies (tested). */
.lib-shot{ position:relative; }
.lib-aichip{ position:absolute; left:10px; bottom:10px; z-index:1; pointer-events:none;
  font-size:12px; font-weight:500; line-height:1; letter-spacing:.03em;
  color:#F2EBE0; background:rgba(27,28,30,.80); padding:6px 10px; border-radius:999px; }
@media (max-width:600px){ .lib-act{ font-size:14px; } }
""" + CSS_END + "\n\n"
CSS_ANCHOR = "/* PLOTNUA A11Y VISUAL v1 · BEGIN"


def die(m):
    print("REFUSED: %s -- nothing written" % m); sys.exit(1)


def strip_layer(t):
    """The page as it would be without this layer, for the byte-for-byte comparison."""
    t = re.sub(r'\n[ \t]*<span class="lib-act">[^<]*</span>', "", t)
    t = re.sub(r'<span class="lib-aichip">[^<]*</span>', "", t)
    i = t.find(CSS_BEGIN)
    if i >= 0:
        j = t.index(CSS_END, i) + len(CSS_END) + 2
        t = t[:i] + t[j:]
    return t


def no_labels(t):
    """Normalise both the old and the new label markup away: what remains must be identical."""
    return OLD_SPANS.sub("", strip_layer(t))


def check_links(page_html):
    return sorted(set(h.split("?")[0] for h in re.findall(r'href="(disc\d{3}-[a-z0-9-]+\.html)(?:\?[^"]*)?"', page_html)))


def prove(key, href, page_html):
    """Return None when the tool is demonstrably on the page, else the reason it is not."""
    if key == "property-check":
        links = check_links(page_html)
        if not links: return "no link to a check page"
        for l in links:
            f = ROOT / l
            if not f.exists(): return "%s does not exist" % l
            t = f.read_text(encoding="utf-8")
            if re.search(r'http-equiv="refresh"', t, re.I): return "%s is a redirect" % l
            if "being prepared" in t.lower(): return "%s says it is being prepared" % l
        return None
    if key == "garden-room-journey":
        return None if 'href="your-plot.html?discovery=garden-room"' in page_html else "no garden room journey link"
    if key == "meet-the-makers":
        return None if "data-pn-supplier-gallery" in page_html else "no live maker gallery"
    if key == "find-what-fits":
        return None if ("data-gb" in page_html and "Show me what fits" in page_html) else "no 'Show me what fits' brief"
    return "unknown label key %r" % key


def main():
    m = json.loads(MAP.read_text(encoding="utf-8"))
    vocab, cards = m["vocabulary"], m["cards"]
    reg = json.loads(REG.read_text(encoding="utf-8"))
    ai_label = reg["labels"]["AI_ILLUSTRATION"]
    ai_records = {r["asset"] for r in reg["records"] if r.get("class") == "AI_ILLUSTRATION"}
    deriv_src = {d["asset"]: d["derived_from"]["asset"] for d in reg["derivatives"]}
    is_ai = lambda src: src in ai_records or deriv_src.get(src) in ai_records

    cur = PAGE.read_text(encoding="utf-8")
    base = OLD_SPANS.sub("", strip_layer(cur))           # labels removed entirely; everything else as live
    found = CARD.findall(base)
    if len(found) != 18 or set(found) != set(cards):   # 16 since DISC-015 (1 Nov 2026); 17 since DISC-020 (4 Nov 2026); 18 since DISC-034 (4 Nov 2026)
        die("the Library cards (%d) do not match the label register (%d)" % (len(found), len(cards)))

    def card(mo):
        block, href = mo.group(0), mo.group(1)
        key = cards[href]
        page_html = (ROOT / href).read_text(encoding="utf-8")
        if key is not None:
            if key not in vocab: die("%s: %r is not in the closed vocabulary" % (href, key))
            why = prove(key, href, page_html)
            if why: die("%s: '%s' cannot be shown -- %s" % (href, vocab[key]["label"], why))
            line = re.search(r'(<span class="lib-line">[^<]*(?:<[^/][^>]*>[^<]*</[^>]+>[^<]*)*</span>)', block)
            if not line: die("%s: description not found" % href)
            indent = re.search(r'\n([ \t]*)<span class="lib-line">', block).group(1)
            block = block.replace(line.group(1), line.group(1) + "\n%s<span class=\"lib-act\">%s</span>" % (indent, vocab[key]["label"]), 1)
        elif "being prepared" not in page_html.lower() and check_links(page_html):
            die("%s has a live check but no label in the register" % href)
        src = re.search(r'<img src="([^"]+)"', block).group(1)
        if is_ai(src):
            shot = re.search(r'(<span class="lib-shot">.*?)(</span>)', block, re.S)
            block = block.replace(shot.group(0), shot.group(1) + '<span class="lib-aichip">%s</span>' % ai_label + shot.group(2), 1)
        return block

    built = CARD.sub(card, base)
    if built.count(CSS_ANCHOR) != 1: die("the stylesheet anchor is not present exactly once")
    built = built.replace(CSS_ANCHOR, CSS + CSS_ANCHOR, 1)
    if no_labels(built) != no_labels(cur): die("something other than the card labels would change")
    n_act, n_chip = built.count('class="lib-act"'), built.count('class="lib-aichip"')
    if CHECK:
        ok = built == cur
        print("LIBRARY CARD LABELS · " + ("OK (%d action labels proven, %d AI chips from declared records, 18 cards)" % (n_act, n_chip)
                                           if ok else "NOT BUILT or out of date"))
        sys.exit(0 if ok else 1)
    PAGE.write_text(built, encoding="utf-8")
    print("built: %d action labels, %d AI chips" % (n_act, n_chip))


if __name__ == "__main__":
    main()
