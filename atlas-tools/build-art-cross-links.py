#!/usr/bin/env python3
"""Add the two founder-approved contextual cross-links between the art
Discoveries (13 October 2026). DISC-023 and DISC-024 stay separate; both URLs,
Property Checks, Search records and My Plot save keys are untouched.

  DISC-024 Open Your Home to Art  -> DISC-023 (in "Three people are better off",
                                     after the "Whoever buys it" line)
  DISC-023 Buy Original Irish Art -> DISC-024 (at the end of the FAQ answer
                                     "Can I see how it will look before I buy?")

Each page gains exactly one link and one small scoped style block (.pn-xlink).

GUARDS
  X1 each page is byte-identical to git HEAD apart from its link and style
  X2 exactly one cross-link per page, to the other page's existing URL
  X3 no new external link, no new URL, no change to either Property Check link
  X4 the style block is in <head>, once

Usage:
  python3 atlas-tools/build-art-cross-links.py --apply | --check
"""
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
STYLE_ANCHOR = "/* PLOTNUA A11Y VISUAL v1 · END */\n</style>"
STYLE = ("\n<style>/* PLOTNUA-ART-XLINK-STYLE · generated by atlas-tools/build-art-cross-links.py */\n"
         ".pn-xlink{color:var(--accent);text-decoration:none;border-bottom:1px solid rgba(79,107,74,.35);"
         "padding-bottom:1px;transition:border-color .35s ease;}\n"
         ".pn-xlink:hover{border-color:var(--accent);}\n"
         ".pn-xlink:focus-visible{outline:2px solid var(--accent);outline-offset:3px;}\n"
         "</style>")

PAGES = {
    "discovery-open-your-home-to-art.html": {
        "anchor": ("<li><span class=\"dq-fact\"><strong>Whoever buys it.</strong> Work seen beside a sofa rather than "
                   "under gallery lighting &mdash; the hardest thing to picture, and the easiest thing to judge.</span>"),
        "insert": ("\n            <span class=\"dq-note\"><!-- PLOTNUA-ART-XLINK -->Thinking of owning a piece yourself? "
                   "<a class=\"pn-xlink\" href=\"discovery-a-home-for-art.html\">Buy Original Irish Art</a> covers finding, "
                   "sizing and commissioning original work <span aria-hidden=\"true\">&rarr;</span></span>"),
        "target": "discovery-a-home-for-art.html",
        "check": "disc024-open-your-home-to-art.html",
    },
    "discovery-a-home-for-art.html": {
        "anchor": ("<div class=\"faq-a\">Some galleries and artists will let you take a work home on approval for a few "
                   "days. It is a courtesy rather than a right, so ask."),
        "insert": ("<!-- PLOTNUA-ART-XLINK --><br><br>The other side of this idea: <a class=\"pn-xlink\" "
                   "href=\"discovery-open-your-home-to-art.html\">Open Your Home to Art</a> looks at giving an "
                   "artist&rsquo;s finished work space in your home <span aria-hidden=\"true\">&rarr;</span>"),
        "target": "discovery-open-your-home-to-art.html",
        "check": "disc023-buy-original-irish-art.html",
    },
}


def die(m):
    print("REFUSED: " + m + " -- nothing written"); sys.exit(2)


def strip(html, spec):
    return html.replace(STYLE_ANCHOR + STYLE, STYLE_ANCHOR).replace(spec["anchor"] + spec["insert"], spec["anchor"])


def build(html, spec):
    base = strip(html, spec)
    if base.count(spec["anchor"]) != 1 or base.count(STYLE_ANCHOR) != 1:
        die("X1 anchor not found exactly once")
    return base.replace(STYLE_ANCHOR, STYLE_ANCHOR + STYLE).replace(spec["anchor"], spec["anchor"] + spec["insert"])


def guards(name, html, spec):
    base = strip(html, spec)
    try:
        head = subprocess.run(["git", "-C", str(ROOT), "show", "HEAD:" + name],
                              capture_output=True, text=True, check=True).stdout
        if strip(head, spec) != base:
            die("X1 %s differs from git HEAD beyond the cross-link" % name)
    except (subprocess.CalledProcessError, FileNotFoundError):
        print("  X1 skipped: git HEAD not available")
    if html.count('class="pn-xlink"') != 1 or html.count('class="pn-xlink" href="%s"' % spec["target"]) != 1:
        die("X2 %s must carry exactly one cross-link to %s" % (name, spec["target"]))
    if not (ROOT / spec["target"]).exists():
        die("X2 target does not exist: " + spec["target"])
    if len(re.findall(r'href="https?://', html)) != len(re.findall(r'href="https?://', base)):
        die("X3 an external link was added")
    if html.count('href="%s"' % spec["check"]) != base.count('href="%s"' % spec["check"]):
        die("X3 the Property Check link changed")
    if html.count("PLOTNUA-ART-XLINK-STYLE") != 1 or html.index("PLOTNUA-ART-XLINK-STYLE") > html.index("</head>"):
        die("X4 style block missing, duplicated or outside <head>")


def main(argv):
    if "--apply" not in argv and "--check" not in argv:
        print(__doc__); sys.exit(1)
    stale = []
    for name, spec in PAGES.items():
        p = ROOT / name
        cur = p.read_text(encoding="utf-8")
        new = build(cur, spec)
        guards(name, new, spec)
        if "--apply" in argv:
            p.write_text(new, encoding="utf-8")
        elif new != cur:
            stale.append(name)
    if stale:
        print("CHECK FAILED: out of date: " + ", ".join(stale)); sys.exit(1)
    print("art cross-links: 2 pages · %s — X1-X4 pass" % ("APPLIED" if "--apply" in argv else "CHECK OK"))


if __name__ == "__main__":
    main(sys.argv[1:])
