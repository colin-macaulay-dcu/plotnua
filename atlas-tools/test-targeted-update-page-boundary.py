#!/usr/bin/env python3
"""TEST — publish-targeted-update.py page-text boundary (outside_text_change), 4 Nov 2026.

Phase 2 supplier integration (founder authorisation): a maker NEW to a page may add only its own
A-Z index lines (one per category, generated by build-maker-explorer.py). Every other change outside
the explorer config must still refuse, exactly as before. Pure-function test on the real
discovery-garden-retreat.html; writes nothing.

  python3 atlas-tools/test-targeted-update-page-boundary.py
"""
import importlib.util, pathlib, sys

HERE = pathlib.Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("ptu", HERE / "publish-targeted-update.py")
T = importlib.util.module_from_spec(spec)
spec.loader.exec_module(T)
PAGE = (HERE.parent / "discovery-garden-retreat.html").read_text(encoding="utf-8")
ORG, TGT = {"Gardenhouse24 Ireland"}, {"recdDCBpXBKOa7leI", "recEDHcHJ5dWaWklV"}
ANCHOR = '        <li><a href="#p-recIy8ghdKxo7PTjP">Hansa24 Group</a>'
fails = []


def line(pid, name, what="4 saunas"):
    return ('        <li><a href="#p-%s">%s</a> <span>%s &middot; Irish availability not yet confirmed</span></li>'
            % (pid, name, what))


def add(text, new):
    i = text.index(ANCHOR)
    return text[:i] + new + "\n" + text[i:]


def case(name, b, expect_ok):
    got = T.outside_text_change(PAGE, b, TGT, ORG)
    ok = (got is None) == expect_ok
    print("  %s  %s%s" % ("PASS" if ok else "FAIL", name, "" if got is None else "  -> " + got[:90]))
    if not ok:
        fails.append(name)


print("PAGE-TEXT BOUNDARY — publish-targeted-update.py")
case("unchanged page", PAGE, True)
case("numbers only change (e.g. 93 -> 97 saunas)", PAGE.replace("93", "97", 1), True)
case("target organisation gains its A-Z line", add(PAGE, line("recdDCBpXBKOa7leI", "Gardenhouse24 Ireland")), True)
case("target gains two A-Z lines", add(add(PAGE, line("recdDCBpXBKOa7leI", "Gardenhouse24 Ireland")),
                                       line("recEDHcHJ5dWaWklV", "Gardenhouse24 Ireland", "2 hot tubs")), True)
case("A-Z line for a product outside --product", add(PAGE, line("recAAAAAAAAAAAAAA", "Gardenhouse24 Ireland")), False)
case("A-Z line naming another maker", add(PAGE, line("recdDCBpXBKOa7leI", "Hansa24 Group")), False)
case("free text in the A-Z span", add(PAGE, line("recdDCBpXBKOa7leI", "Gardenhouse24 Ireland", "best value, 4 saunas")), False)
case("a new availability claim in the A-Z span", add(PAGE, '        <li><a href="#p-recdDCBpXBKOa7leI">Gardenhouse24 Ireland</a> <span>4 saunas &middot; Irish availability guaranteed</span></li>'), False)
case("an arbitrary added sentence", add(PAGE, "        <p>Our recommended sauna.</p>"), False)
case("a claim smuggled into the A-Z span", add(PAGE, '        <li><a href="#p-recdDCBpXBKOa7leI">Gardenhouse24 Ireland</a> <span>best value <b>x</b></span></li>'), False)
case("an existing line removed", PAGE.replace(ANCHOR, "", 1), False)
case("an existing line edited", PAGE.replace("Recommendations cannot be bought", "Recommendations can be bought", 1), False)
case("the referral disclosure removed", PAGE.replace("Current commercial relationship: TimberIN", "", 1), False)
print("-" * 60)
print("%s — %d failure(s)" % ("ALL PASS" if not fails else "FAILURES", len(fails)))
sys.exit(1 if fails else 0)
